  $PY - "$VIEWS" "$OUTDIR/views.mut.bin" <<'MUTEOF' >"$OUTDIR/mut1.log" 2>&1
import sys, struct
src, dst = sys.argv[1], sys.argv[2]
d = bytearray(open(src, "rb").read())
off = 8
while off + 8 <= len(d):
    tag = bytes(d[off:off+4]).decode("latin1")
    ln = struct.unpack("<I", bytes(d[off+4:off+8]))[0]
    if tag == "BGCH":
        # the LAST byte of the BG chr view: block 47, the one the round robin
        # reaches last, so a player that only ever drains the head fails here.
        p = off + 8 + ln - 1
        d[p] ^= 0xFF
        print("BGCH[%d] -> $%02X" % (ln - 1, d[p]))
        break
    off += 8 + ln
else:
    raise SystemExit("*** views sem secao BGCH")
open(dst, "wb").write(bytes(d))
MUTEOF
