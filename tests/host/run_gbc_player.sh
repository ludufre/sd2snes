src, dst, pairs = sys.argv[1], sys.argv[2], sys.argv[3:]
s = open(src).read()
for old, new in zip(pairs[0::2], pairs[1::2]):
    n = s.count(old)
    if n != 1:
        sys.exit("alvo do mutante aparece %d vez(es): %r" % (n, old[:60]))
    s = s.replace(old, new)
open(dst, "w").write(s)
PYEOF
      then
        echo "FAIL  (MBX mut) '$nm': $(cat "$OUTDIR/mbxmut.log")"; fail=$((fail+1)); return
      fi
