def diff(name, got, want, limit=6):
    if got == want:
        return 0
    n = 0
    lines = []
    for i in range(min(len(got), len(want))):
        if got[i] != want[i]:
            n += 1
            if len(lines) < limit:
                lines.append("  %s[$%04X] player=$%02X ideal=$%02X" % (name, i, got[i], want[i]))
