  fi

  if asar_ok; then
    mbx_mutant() { # <nome> <old> <new> [<old> <new>...]
      local nm="$1" ma="$OUTDIR/mbxmut.asm" mb="$OUTDIR/mbxmut.bin" mm="$OUTDIR/mbxmut.map"
      shift
      rm -f "$mm" "$mb"
      if ! $PY - "$ASM" "$ma" "$@" <<'PYEOF' >"$OUTDIR/mbxmut.log" 2>&1
