          --symbols-path=mbxmut.sym mbxmut.asm mbxmut.bin ) >>"$OUTDIR/mbxmut.log" 2>&1 &&
      $PY "$REPO_ROOT/snes/gbc/gen_map_asar.py" "$OUTDIR/mbxmut.sym" "$mb" "$mm" \
          >>"$OUTDIR/mbxmut.log" 2>&1
      if [ ! -f "$mm" ]; then
        echo "FAIL  (MBX mut) '$nm' nao montou:"; sed 's/^/      /' "$OUTDIR/mbxmut.log" | head -4
        fail=$((fail+1)); return
