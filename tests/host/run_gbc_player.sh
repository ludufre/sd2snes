#!/usr/bin/env bash
# Offline gate for the Game Boy Color SNES-side player (snes/gbc/gbc_snes.asm).
#
# The player is 65816 assembly and the only honest way to test it without a
# console is to EXECUTE it.  gbc_render_cli.c loads misc/gbc_snes_harness.bin
# into the 65816 interpreter (m65816.c), runs the ROM's OWN Reset -- register
# bring-up, VRAM/CGRAM/OAM clear, HDMA tables, wire-version handshake, GO --
# and then calls GbcFrameOnce once per frame against views served from a GBVW
# file.  Nothing here reimplements the transfer engine: the dirty-bit fold,
# the persistent backlog, the round-robin, the coalescing, the budget
# arithmetic and the V guard are all the real assembly's.
#
# What the gate is:  VRAM/CGRAM/OAM byte-exact against the IDEAL player,
# gbc/tests/viewsim/snes_model.py (the offline gate).
#
# NOT the gate: the rendered PICTURE.  cgb-acid2 changes LCDC.0/2/3/4/5/6 in
# mid-frame and contract sec. 12.5 declares per-line LCDC unsupported in phase
# 2, so a static render is 1.939 px off the corpus PNG BY DESIGN.  The state
# the player leaves in VRAM/CGRAM/OAM, however, must equal the ideal player's
# to the byte -- that is what this file checks.  The picture gate lives in
# gbc/tests/viewsim/gate.py, which applies the per-line schedule.
#
# ADDRESSES COME FROM THE BUILD.  misc/gbc_snes_harness.map is generated by
# snes/gbc/gen_map_asar.py out of asar's own symbol dump and stamps the .bin's
# size and CRC32, so the CLI refuses a desynchronised pair.  The layout and
# budget constants are extracted from gbc_snes.asm by awk below and passed as
# -D -- no number of the player's is duplicated in C (same discipline as
# run_nes_chr.sh with nes_equates.i65).
#
# SKIP: misc/gbc_snes_harness.bin is not versioned and needs asar, which macOS
# does not have natively, so a clean clone skips and the gate exits 0.
# GBC_BIN_REQUIRED=1 turns every reason for checking nothing into a failure.
#
# LIMIT -- WHAT THIS GATE STRUCTURALLY CANNOT SEE.  V is a PARAMETER here
# (--v, default 230), not a counter: it does not advance while the frame body
# runs, so nothing measures how much of window A the body actually costs, and
# any test the player makes against the live scanline sees a constant.  Two
# real bugs hid in exactly that blind spot and were found by the bsnes-plus
# harness instead:
#   * GbcReadyCheck used to gate the screen release on "V >= 225".  Here that
#     is always true, so --require-converged reported ready_frame = 3 and the
#     gate was green -- while on real timing the body ended at V=48, the test
#     was false in every frame, and the player never left forced blank.
#   * the same pinning makes the deadline unreachable, so a DMA that would
#     overrun the window on silicon simply cannot be observed as a drop.
# Everything about the arm, the body's cost in lines and the real deadline is
# the bsnes-plus gate's job (gbc/tests/renderer-harness).  What lives HERE is
# the transfer engine: fold, backlog, round-robin, coalescing, block-exact
# addressing and the byte-exact result.
#
# ⚡ PHASE 5 CLOSED MOST OF THAT BLIND SPOT FOR THE BLOCK (P5) BELOW: --clock
# runs the real main loop on a master-cycle clock in m65816.c (bus-region
# speeds, internal cycles, DMA at 8 mc/byte, DRAM refresh, the sec. 11.1 HDMA
# tax, NMI at V=225, the V-IRQ at VTIME, WAI), with the CLI playing the bridge.
# Every other block still pins V; the clock is a MODEL (~26 mc/instruction on
# the player's code, against ~29.5 measured in bsnes-plus in phase 4), so its
# numbers are for before/after comparisons, not a replacement for silicon.
#
# ONE THING THAT DID BECOME OBSERVABLE HERE: the raster compiler runs in the
# MAIN LOOP and the NMI interrupts it, and GbcFrameOnce -- body then compile,
# back to back -- is the one shape that cannot test that.  --interleave runs
# the compile in slices and injects a whole frame body between them (block
# (P4-NMI) below), which is what turns "the body must not touch the buffers
# the compile is reading" from a comment into a measurement.
#
# THE ASSEMBLER: a reassembly is needed for every mutant, and `asar` on PATH is
# very often npm's Electron packer rather than the assembler.  asar_ok() below
# tells them apart by the --version banner and treats the wrong one as absent,
# because the alternative is a gate that silently tests a stale image.
#
# HISTORY: this file was born RED.  (A2) and the two partial-map cases of (I)
# failed on a real player bug -- the direct page $58 had two owners inside the
# drain, so a map class whose run was not a multiple of four blocks walked off
# the end of its own backlog and DMAd the wrong view into the wrong VRAM
# region.  Fixed in the player (the walk start moved to $61); the cases stayed,
# and 'map:0-2' / 'map:2-4' are still exactly the shapes that would catch it
# again.
set -u
cd "$(dirname "$0")"
CC="${CC:-cc}"
. ./sanitizers.sh   # ASAN_OPTIONS/UBSAN_OPTIONS + san_report(); see the file
PY="${PYTHON:-python3}"
REPO_ROOT="../.."
ASM="$REPO_ROOT/snes/gbc/gbc_snes.asm"
OUTDIR=build/gbc
mkdir -p "$OUTDIR"

pass=0; fail=0; skip=0

# The viewsim model and the SameBoy state dump are not part of this repository
# (like run_cfg.sh's golden corpus): a run without them falls back
# to synthetic views plus the inline sec. 11.2 model at the bottom of this file.
VIEWSIM="${GBC_VIEWSIM:-../../../gbc/tests/viewsim}"
SB_STATE="${GBC_SB_STATE:-../../../gbc/tests/rtl-tb/sameboy/work/cgb-acid2.gbc.sameboy.bin}"
# Phase-4 golden fixtures: {status.bin, log.bin, cram.bin} in, the six HDMA
# tables + $420C + the counters out.  Same discipline as the viewsim model
# above -- they are not part of this repository, so a run without them SKIPs instead of
# failing, and GBC_FIXTURES_REQUIRED=1 turns the skip back into a failure.
FIXTURES="${GBC_FIXTURES:-../../../gbc/tests/viewsim/fixtures_p4}"
FIX_REQUIRED="${GBC_FIXTURES_REQUIRED:-0}"

# ---------------------------------------------------------------------------
# 1) constants, straight out of the .asm
# ---------------------------------------------------------------------------
asm_def() { # !NAME = value        -> value ($HEX becomes 0xHEX)
  awk -v n="!$1" '$1==n && $2=="=" { v=$3; sub(/^\$/, "0x", v); print v; exit }' "$ASM"
}
asm_ctr() { # !NAME = !GBC_CTR+$xx -> 0xxx
  awk -v n="!$1" '$1==n && $2=="=" { v=$3; sub(/^!GBC_CTR\+/, "", v);
                                     sub(/^\$/, "0x", v); print v; exit }' "$ASM"
}

[ -f "$ASM" ] || { echo "*** $ASM ausente"; exit 1; }
DEFS=""
for n in GBC_BUDGET GBC_DMACOST GBC_VER \
         GBC_ST_VER GBC_ST_FLAGS0 GBC_ST_SEQ GBC_ST_DCHR GBC_ST_DOBJ \
         GBC_ST_DMAP GBC_ST_DMISC GBC_ST_SCX GBC_ST_LOGN \
         GBC_SNAP_LEN GBC_LOG_MAX GBC_BPLHDMA GBC_DEADLINE GBC_CLS_N \
         GBC_T_W1 GBC_T_CH0 GBC_T_SLOT GBC_T_INIDISP \
         GBC_SETA_OFF GBC_SETB_OFF GBC_H_MASK GBC_H_CH \
         GBC_EFO_COMMIT GBC_EFO_GO GBC_EFO_SYNC GBC_EFO_CONSUME \
         GBC_EFO_MBX GBC_MBX_N \
         GBC_ST_C6FLAGS GBC_ST_ROWF GBC_ST_C6CL GBC_ST_C6DIRTY GBC_ST_RCLI \
         GBC_ST_COLWN GBC_EFO_C6CTL GBC_EFO_ROWDONE GBC_WHITE_HOLD; do
  v=$(asm_def "$n")
  [ -n "$v" ] || { echo "*** constante !$n ausente de $ASM"; exit 1; }
  DEFS="$DEFS -D$n=$v"
done
for n in GBC_CTR_FRAMES GBC_CTR_DMAS GBC_CTR_BYTES GBC_CTR_DEFER \
         GBC_CTR_DROPS GBC_CTR_READY GBC_CTR_REGSLATE; do
  v=$(asm_ctr "$n")
  [ -n "$v" ] || { echo "*** contador !$n ausente de $ASM"; exit 1; }
  DEFS="$DEFS -D$n=$v"
done
echo "== build =="
NCLS_N=$(asm_def GBC_CLS_N)
echo "  constantes (de $(basename "$ASM")): budget=$(asm_def GBC_BUDGET) dmacost=$(asm_def GBC_DMACOST) ver=$(asm_def GBC_VER) classes=$NCLS_N"

$CC -O1 -g -fsanitize=address,undefined -I. $DEFS \
    m65816.c gbc_c6.c gbc_render_cli.c -o "$OUTDIR/gbc_render_cli" || exit 1
CLI="./$OUTDIR/gbc_render_cli"

# ---------------------------------------------------------------------------
# 2) the interpreter's own self-test -- everything below is premised on it,
#    and it needs no player image, so a clean clone still checks it.
# ---------------------------------------------------------------------------
if out=$($CLI --selftest 2>&1); then
  echo "PASS  m65816 selftest (65816 + barramento + extensoes GBC)"
  pass=$((pass+1))
else
  echo "FAIL  m65816 selftest:"; echo "$out" | sed 's/^/      /'
  fail=$((fail+1))
fi

# ---------------------------------------------------------------------------
# 3) the player image
# ---------------------------------------------------------------------------
ASAR="${ASAR:-asar}"
BIN="${GBC_SNES_BIN:-$REPO_ROOT/misc/gbc_snes_harness.bin}"
MAP="${GBC_SNES_MAP:-${BIN%.bin}.map}"
REQUIRED="${GBC_BIN_REQUIRED:-0}"

# ---------------------------------------------------------------------------
# IS THIS asar THE ASSEMBLER?  `command -v asar` is not the question: npm's
# `asar` is Electron's archive packer and answers it just as happily, and then
# every reassembly here dies with "unknown option '-DGBC_HARNESS=1'" while the
# gate keeps running against whatever .bin was already on disk.  The assembler
# prints "Asar <version>" for --version; the packer prints a bare number.
# Anything that is not the assembler is treated as NO ASSEMBLER.
asar_why=""
asar_ok() { [ -z "$asar_why" ]; }
if ! command -v "$ASAR" >/dev/null 2>&1; then
  asar_why="asar nao esta' no PATH (\$ASAR = '$ASAR')"
elif ! "$ASAR" --version 2>/dev/null | head -1 | grep -qi '^Asar '; then
  asar_why="'$ASAR' nao responde 'Asar <versao>' a --version -- o 'asar' do npm"
  asar_why="$asar_why e' o empacotador do Electron, nao o assembler"
fi
if [ -n "$asar_why" ]; then echo "  aviso: $asar_why"; fi

# How many cases each block WOULD check, so a SKIP is never mute.
planned=74
p4_planned=90

gbc_skip() { # <motivo>
  if [ "$REQUIRED" != "0" ]; then
    echo "FAIL: $1" >&2
    echo "      GBC_BIN_REQUIRED esta' setado, entao nao executar o player e' falha." >&2
    echo "      Rode 'make -C snes/gbc harness ASAR=<asar>' (asar nao e' nativo do macOS)," >&2
    echo "      ou aponte \$GBC_SNES_BIN/\$GBC_SNES_MAP para um par valido." >&2
    fail=$((fail+1))
    return 1
  fi
  echo "SKIP  player ($((planned + p4_planned)) casos nao checados): $1"
  skip=$((planned + p4_planned))
  return 1
}

if asar_ok; then
  make -C "$REPO_ROOT/snes/gbc" harness ASAR="$ASAR" >"$OUTDIR/asar.log" 2>&1 || {
    echo "FAIL  build do harness do player:"; sed 's/^/      /' "$OUTDIR/asar.log"
    fail=$((fail+1))
  }
fi

# No assembler AND an image older than the source: every case below would be
# testing a player that is not the one in the tree, and the (bin, map) pair
# check cannot see it -- the two are stale TOGETHER and agree perfectly.
bin_stale=0
if ! asar_ok && [ -f "$BIN" ] && [ "$ASM" -nt "$BIN" ]; then bin_stale=1; fi

run_all() {
  [ "$bin_stale" = 0 ] || { gbc_skip "$(basename "$BIN") e' mais velho que $(basename "$ASM") e nao ha' asar para refaze-lo -- o par (.bin,.map) esta' stale JUNTO e passaria na checagem de CRC"; return; }
  [ -f "$BIN" ] || { gbc_skip "$BIN ausente -- nao versionado, sai de 'make -C snes/gbc harness'"; return; }
  [ -f "$MAP" ] || { gbc_skip "$MAP ausente -- sai junto do .bin (gen_map_asar.py)"; return; }
  echo "  player: $BIN ($(wc -c < "$BIN" | tr -d ' ') B) + $(basename "$MAP")"

  # -------------------------------------------------------------------------
  # 4) views.  Preferred: the REAL cgb-acid2 state through viewsim's views.py.
  #    Fallback (no viewsim): a deterministic synthetic GBVW built here.
  # -------------------------------------------------------------------------
  VIEWS="$OUTDIR/views.bin"
  VIEWS_SRC=""
  if [ -f "$VIEWSIM/views.py" ] && [ -f "$SB_STATE" ]; then
    if $PY "$VIEWSIM/views.py" "$SB_STATE" -o "$PWD/$VIEWS" --snap-valid \
         >"$OUTDIR/views.log" 2>&1; then
      VIEWS_SRC="viewsim/views.py sobre $(basename "$SB_STATE")"
    else
      echo "  aviso: views.py falhou, caindo no GBVW sintetico:"
      sed 's/^/        /' "$OUTDIR/views.log"
    fi
  fi
  if [ -z "$VIEWS_SRC" ]; then
    $PY "$OUTDIR/mkviews.py" "$VIEWS" "$(asm_def GBC_VER)" >"$OUTDIR/views.log" 2>&1 || {
      echo "FAIL  geracao das views sinteticas:"; sed 's/^/      /' "$OUTDIR/views.log"
      fail=$((fail+1)); return; }
    VIEWS_SRC="GBVW sintetico deterministico (sem viewsim)"
  fi
  echo "  views: $VIEWS ($(wc -c < "$VIEWS" | tr -d ' ') B) -- $VIEWS_SRC"

  # -------------------------------------------------------------------------
  # 5) how many frames the full refresh needs.  MEASURED, not assumed: the
  #    contract publishes ~3 frames for a total refresh and the player's own
  #    header says 3.3 windows, but the number that matters is what THIS
  #    binary does, and it moves with every budget constant.
  # -------------------------------------------------------------------------
  NCONV=0
  for n in 1 2 3 4 5 6 7 8 10 12; do
    if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
            --frames "$n" --dirty 'all;none' --require-converged \
            >"$OUTDIR/conv.$n.log" 2>&1; then NCONV=$n; break; fi
  done
  if [ "$NCONV" -eq 0 ]; then
    echo "FAIL  o refresh total nao fechou em 12 frames:"
    sed 's/^/      /' "$OUTDIR/conv.12.log"
    fail=$((fail+1)); return
  fi
  echo "  convergencia do refresh total: $NCONV frames (medido)"

  # -------------------------------------------------------------------------
  # (A) THE GATE: VRAM/CGRAM/OAM byte-exact against snes_model.py
  # -------------------------------------------------------------------------
  A_FRAMES=$((NCONV > 6 ? NCONV : 6))
  if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
          --frames "$A_FRAMES" --dirty 'all;none' \
          --require-converged --require-no-defer-last --budget-mode \
          --dump-snes "$OUTDIR/A.snst" >"$OUTDIR/A.log" 2>&1; then
    echo "PASS  (A) $A_FRAMES frames: convergiu, sem trabalho adiado no ultimo"
    pass=$((pass+1))
  else
    echo "FAIL  (A) run do player:"; sed 's/^/      /' "$OUTDIR/A.log"
    fail=$((fail+1))
  fi
  grep -E '^(boot|frame|counters|budget|kinds)' "$OUTDIR/A.log" | sed 's/^/      /'

  if [ -f "$OUTDIR/A.snst" ]; then
    if GBC_VIEWSIM="$VIEWSIM" $PY "$OUTDIR/cmp_snes.py" "$OUTDIR/A.snst" "$VIEWS" \
         >"$OUTDIR/A.cmp.log" 2>&1; then
      echo "PASS  (A) VRAM/CGRAM/OAM == o player ideal (byte-exato)"
      pass=$((pass+1))
      sed 's/^/      /' "$OUTDIR/A.cmp.log"
    else
      echo "FAIL  (A) divergencia vs o player ideal:"
      sed 's/^/      /' "$OUTDIR/A.cmp.log"
      fail=$((fail+1))
    fi
  fi

  # (A2) o mesmo gate byte-exato sob sobrecarga CONTINUA.
  #
  # ⚠ COM A VIEW PARADA ESTE CASO E' VACUO.  Se a view nao muda entre frames,
  # uma classe que transferiu no frame 1 e nunca mais deixa a VRAM IDENTICA a'
  # do player ideal -- a comparacao byte-exata e' estruturalmente cega para
  # isso.  Entao a sujeira e' renovada todo frame COM CONTEUDO QUE MUDA:
  # `--view-churn` vira um byte de cada classe que o spec pede, a cada frame,
  # e grava no fim a GBVW que o bridge esta' publicando AGORA -- e e' contra
  # ela que o `cmp_snes.py` compara.  O player tem de ter acompanhado as
  # mudancas, nao so' o boot.  (Quem refuta STARVATION e' o (C); este prova
  # que a imagem converge para o conteudo corrente.)
  A2_SPEC=$($PY -c "print(';'.join(['all']*24+['none']))")
  A2_FRAMES=$((24 + 3 * NCLS_N))
  if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
          --frames "$A2_FRAMES" --dirty "$A2_SPEC" \
          --view-churn "$OUTDIR/A2.views.bin" \
          --dump-snes "$OUTDIR/A2.snst" >"$OUTDIR/A2.log" 2>&1 &&
     GBC_VIEWSIM="$VIEWSIM" $PY "$OUTDIR/cmp_snes.py" "$OUTDIR/A2.snst" \
          "$OUTDIR/A2.views.bin" >"$OUTDIR/A2.cmp.log" 2>&1; then
    echo "PASS  (A2) $A2_FRAMES frames, 24 deles com a view MUDANDO: converge byte-exato"
    pass=$((pass+1))
  else
    echo "FAIL  (A2) sobrecarga continua com a view mudando:"
    grep -hE '^(FAIL|\*\*\*)' "$OUTDIR/A2.log" "$OUTDIR/A2.cmp.log" 2>/dev/null | sed 's/^/      /' | head -6
    fail=$((fail+1))
  fi

  # (G) the poison has to be LIVE, or every check above is comparing the boot's
  # zeros with the model's zeros.  After a single frame the OBJ chr region is
  # untouched (frame 1 spends its whole window on BG chr), so it must still be
  # full of $A5.
  $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" --frames 1 --dirty 'all' \
       --dump-snes "$OUTDIR/G.snst" >"$OUTDIR/G.log" 2>&1
  if $PY - "$OUTDIR/G.snst" <<'PEOF' >"$OUTDIR/G.cmp.log" 2>&1
import struct, sys
d = open(sys.argv[1], "rb").read()
assert d[:4] == b"SNST"
off, vram = 8, None
while off + 8 <= len(d):
    tag = d[off:off+4].decode("latin1")
    ln = struct.unpack("<I", d[off+4:off+8])[0]
    if tag == "VRAM": vram = d[off+8:off+8+ln]
    off += 8 + ln
n = vram[0x0000:0x4000].count(0xA5)
print("OBJ chr apos 1 frame: %d de 16384 bytes ainda envenenados" % n)
if n < 16000:
    raise SystemExit("*** o envenenamento nao esta' vivo (ou o frame 1 copiou OBJ chr)")
PEOF
  then
    echo "PASS  (G) envenenamento vivo: $(sed -n 1p "$OUTDIR/G.cmp.log")"
    pass=$((pass+1))
  else
    echo "FAIL  (G) envenenamento:"; sed 's/^/      /' "$OUTDIR/G.cmp.log"
    fail=$((fail+1))
  fi

  # -------------------------------------------------------------------------
  # (J) LCD OFF: the contract's white screen (sec. 11.3).
  #
  # This case exists because the bsnes-plus harness found a bug here that this
  # one structurally could not: GbcWhiteMap used a FIXED-source DMA in mode 1
  # over a two-byte word, and with the A-bus held still the 5A22 feeds the same
  # byte to $2118 and $2119 -- so the map came out as $0101 (tile 257) instead
  # of $0301 (tile 769, solid colour 2) and the viewport went black where the
  # contract wants white.  m65816.c models fixed-source DMA correctly; there
  # simply was no LCD-off scenario to run it in.
  #
  # NOT --require-converged: with the LCD off the player deliberately leaves
  # the BG-carpet class in the backlog (the white map owns BG4's VRAM), so the
  # backlog never empties.  The ideal model does the same thing by a different
  # route -- it lays the carpet down and then paints white over it -- and the
  # two agree on the bytes, which is what is being checked.
  # -------------------------------------------------------------------------
  VIEWS_OFF="$OUTDIR/views_lcdoff.bin"
  $PY - "$VIEWS" "$VIEWS_OFF" <<'PEOF' >"$OUTDIR/J.mk.log" 2>&1
import struct, sys
d = bytearray(open(sys.argv[1], "rb").read())
assert d[:4] == b"GBVW", "nao e' um GBVW"
off = 8
while off + 8 <= len(d):
    tag = bytes(d[off:off+4]); ln = struct.unpack("<I", d[off+4:off+8])[0]
    if tag == b"STAT":
        d[off+8+1] &= ~0x01        # flags0 bit 0 = LCD_ON
        break
    off += 8 + ln
else:
    raise SystemExit("*** secao STAT nao encontrada")
open(sys.argv[2], "wb").write(bytes(d))
PEOF
  if [ ! -s "$VIEWS_OFF" ]; then
    echo "FAIL  (J) nao consegui montar as views de LCD off:"
    sed 's/^/      /' "$OUTDIR/J.mk.log"; fail=$((fail+1))
  else
  $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS_OFF" --frames 8 --dirty 'all;none' \
       --dump-snes "$OUTDIR/J.snst" >"$OUTDIR/J.log" 2>&1
  if [ -f "$OUTDIR/J.snst" ] && $PY - "$OUTDIR/J.snst" <<'PEOF' >"$OUTDIR/J.cmp.log" 2>&1
import struct, sys
d = open(sys.argv[1], "rb").read()
assert d[:4] == b"SNST"
off, sec = 8, {}
while off + 8 <= len(d):
    tag = d[off:off+4].decode("latin1")
    ln = struct.unpack("<I", d[off+4:off+8])[0]
    sec[tag] = d[off+8:off+8+ln]
    off += 8 + ln
vram, regs = sec["VRAM"], sec["REGS"]
# wire $02: the white map lives in FREE VRAM ($A000) and BG4 is pointed AT it
# with $210A instead of it being painted over the carpet map.  Checking the
# register too is the point -- a map written to the right place and not
# selected shows the carpet, and a map selected but never written shows noise.
bg4 = regs[0x0A]
if bg4 != 0x50:
    raise SystemExit("*** $210A = $%02X, esperado $50 (BG4 no mapa branco de "
                     "$A000)" % bg4)
got = vram[0xA000:0xA800]
want = bytes([0x01, 0x03]) * 1024
if got != want:
    bad = sum(1 for a, b in zip(got, want) if a != b)
    raise SystemExit("*** o mapa branco nao e' 1024 x {t=769,pal=0}: %d de 2048 bytes "
                     "diferentes, comeca com %s (esperado 01 03 01 03)"
                     % (bad, " ".join("%02X" % c for c in got[:8])))
tm = regs[0x2C]
if tm != 0x08:
    raise SystemExit("*** TM = $%02X, esperado $08 (so' BG4)" % tm)
print("mapa branco em $A000 = 1024 x $0301 (tile 769), $210A = $50, TM = $08")
PEOF
  then
    echo "PASS  (J) LCD off: $(sed -n 1p "$OUTDIR/J.cmp.log")"
    pass=$((pass+1))
  else
    echo "FAIL  (J) LCD off, tela branca:"
    sed 's/^/      /' "$OUTDIR/J.cmp.log" 2>/dev/null
    grep -hE '^FAIL' "$OUTDIR/J.log" 2>/dev/null | sed 's/^/      /'
    fail=$((fail+1))
  fi
  GBC_VIEWSIM="$VIEWSIM" $PY "$OUTDIR/cmp_snes.py" \
       "$OUTDIR/J.snst" "$VIEWS_OFF" --model-required >"$OUTDIR/J.model.log" 2>&1
  case $? in
    0) echo "PASS  (J) LCD off == o player ideal (byte-exato)"; pass=$((pass+1));;
    77) echo "SKIP  (J) LCD off vs o player ideal: $(sed -n 1p "$OUTDIR/J.model.log")"
        skip=$((skip+1));;
    *) echo "FAIL  (J) LCD off vs o player ideal:"
       sed 's/^/      /' "$OUTDIR/J.model.log" 2>/dev/null
       fail=$((fail+1));;
  esac
  fi

  # -------------------------------------------------------------------------
  # gbc_views_patch <out> <python on the STAT bytearray `st`>
  # STAT offsets: 0 ver, 1 flags0 (b0 LCD_ON, b2 COMPAT, b5 FIRST_FRAME),
  # 2 LCDC, 3 SCX, 4 SCY, 5 WX, 6 WY.
  # -------------------------------------------------------------------------
  gbc_views_patch() {
    local out="$1"; shift
    $PY - "$VIEWS" "$out" "$*" <<'PEOF'
import struct, sys
d = bytearray(open(sys.argv[1], "rb").read())
assert d[:4] == b"GBVW", "nao e' um GBVW"
off = 8
while off + 8 <= len(d):
    tag = bytes(d[off:off+4]); ln = struct.unpack("<I", d[off+4:off+8])[0]
    if tag == b"STAT":
        st = bytearray(d[off+8:off+8+ln])
        exec(sys.argv[3])
        d[off+8:off+8+ln] = st
        break
    off += 8 + ln
else:
    raise SystemExit("*** secao STAT nao encontrada")
open(sys.argv[2], "wb").write(bytes(d))
PEOF
  }

  # A byte-exact run against snes_model.py with a patched status block.
  # gbc_model_case <nome> <arquivo> <patch python>
  gbc_model_case() {
    local nm="$1" f="$2"; shift 2
    gbc_views_patch "$OUTDIR/$f" "$@" >"$OUTDIR/$f.mk.log" 2>&1 || {
      echo "FAIL  ($nm) montagem das views:"; sed 's/^/      /' "$OUTDIR/$f.mk.log"
      fail=$((fail+1)); return; }
    $CLI --rom "$BIN" --map "$MAP" --views "$OUTDIR/$f" --frames 8 \
         --dirty 'all;none' --dump-snes "$OUTDIR/$f.snst" >"$OUTDIR/$f.log" 2>&1
    [ -f "$OUTDIR/$f.snst" ] || { echo "FAIL  ($nm): o player abortou"
      grep -hE '^FAIL' "$OUTDIR/$f.log" 2>/dev/null | sed 's/^/      /'
      fail=$((fail+1)); return; }
    # These cases patch the STATUS BLOCK, not the views, so the inline sec.
    # 11.2 fallback answers with the plain picture for every one of them and
    # would call a correct player wrong (LCD off) or right for the wrong
    # reason (the clamps).  It is a SKIP there, not a verdict.
    GBC_VIEWSIM="$VIEWSIM" $PY "$OUTDIR/cmp_snes.py" \
         "$OUTDIR/$f.snst" "$OUTDIR/$f" --model-required >"$OUTDIR/$f.cmp.log" 2>&1
    case $? in
      0) echo "PASS  ($nm)"; pass=$((pass+1));;
      77) echo "SKIP  ($nm): $(sed -n 1p "$OUTDIR/$f.cmp.log")"; skip=$((skip+1));;
      *) echo "FAIL  ($nm):"
         sed 's/^/      /' "$OUTDIR/$f.cmp.log" 2>/dev/null | head -8
         grep -hE '^FAIL' "$OUTDIR/$f.log" 2>/dev/null | sed 's/^/      /'
         fail=$((fail+1));;
    esac
  }

  # -------------------------------------------------------------------------
  # (K) THE WHITE SCREEN MUST ALSO EMPTY WINDOW 1.
  #
  # $2124 = $EF masks BG4 W1-IN and the LCD-off screen enables BG4 alone, so a
  # window that is still switched on cuts a black hole (the backdrop) out of
  # what the contract says is white.  Real trigger: Pokemon R/B/Y switches the
  # LCD off with `and $7F`, which keeps LCDC.5; and EVERY LCD-on with a window
  # goes through one FIRST_FRAME frame.  With WX=7/WY=0 the hole is the entire
  # 160x144.  Both the player and snes_model.py had it, which is why no gate
  # saw it -- the model was fixed in the same round, so this compares two
  # independently corrected sides.
  # -------------------------------------------------------------------------
  gbc_model_case "K: LCD off + janela ligada => W1 vazia" views_offwin.bin \
      'st[1] &= ~0x01; st[2] |= 0x20; st[5] = 7; st[6] = 0'
  gbc_model_case "K2: FIRST_FRAME + janela ligada => W1 vazia" views_ffwin.bin \
      'st[1] |= 0x21; st[2] |= 0x20; st[5] = 7; st[6] = 0'
  # ... and the table really is 224 empty entries, not just "close to the model"
  if [ -f "$OUTDIR/views_offwin.bin.snst" ] && $PY - "$OUTDIR/views_offwin.bin.snst" \
       <<'PEOF' >"$OUTDIR/K.w1.log" 2>&1
import struct, sys
d = open(sys.argv[1], "rb").read()
off, sec = 8, {}
while off + 8 <= len(d):
    tag = d[off:off+4].decode("latin1"); ln = struct.unpack("<I", d[off+4:off+8])[0]
    sec[tag] = d[off+8:off+8+ln]; off += 8 + ln
h = sec["HDMA"]; half = len(h) // 2
rows = []
for si in (0, 1):
    t = h[si*half + 0x100:]                 # !GBC_T_W1 inside the set
    i, n = 0, 0
    while t[i]:
        cnt = t[i] & 0x7F
        rows += [(t[i+1], t[i+2])] * cnt
        i += 3; n += cnt
    if n != 224:
        raise SystemExit("*** set %d cobre %d linhas, esperado 224" % (si, n))
if set(rows) != {(255, 0)}:
    raise SystemExit("*** W1 nao esta' vazia: %s" % sorted(set(rows)))
print("os DOIS sets: 224 linhas, todas (255,0)")
PEOF
  then
    echo "PASS  (K) W1 = (255,0) x224 nos dois sets: $(sed -n 1p "$OUTDIR/K.w1.log")"
    pass=$((pass+1))
  else
    echo "FAIL  (K) tabela W1:"; sed 's/^/      /' "$OUTDIR/K.w1.log"; fail=$((fail+1))
  fi

  # (L) sec. 13.13: compat with LCDC.0 = 0 drops the two content layers and
  # keeps the carpets, because the carpets paint BG[0][BGP&3] -- exactly the
  # pixel the hardware shows there.
  gbc_model_case "L: compat + LCDC.0=0 => TM=\$1C" views_compat.bin \
      'st[1] |= 0x04; st[2] &= ~0x01'

  # (M) the window-1 clamps, one file each (contract sec. 11.3).
  gbc_model_case "M: WX<7 encosta na borda do viewport" views_wxlo.bin \
      'st[2] |= 0x20; st[5] = 3; st[6] = 20'
  gbc_model_case "M: WX>=167 esconde a janela" views_wxhi.bin \
      'st[2] |= 0x20; st[5] = 167; st[6] = 20'
  gbc_model_case "M: WY>143 esconde a janela" views_wyhi.bin \
      'st[2] |= 0x20; st[5] = 7; st[6] = 200'

  # -------------------------------------------------------------------------
  # (N) sec. 10: the bridge disappears and comes back.
  #
  # ver == $00 must stop the re-render dead (only the status DMA runs), and the
  # frame it answers again it must get a GO: GbcLifeWait can time out at boot
  # without ever reaching GbcGo, and then the player would fold, apply
  # registers and drain the views of a GB that is still held in reset.
  # -------------------------------------------------------------------------
  if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" --frames 6 --dirty 'all' \
          --ver-late 3 --require-go 2 >"$OUTDIR/N.log" 2>&1; then
    echo "PASS  (N) bridge some por 3 frames e volta: GO re-emitido"
    pass=$((pass+1))
  else
    echo "FAIL  (N) recuperacao da bridge:"; sed 's/^/      /' "$OUTDIR/N.log" | head -6
    fail=$((fail+1))
  fi
  # and while it is away nothing but the status block moves
  if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" --frames 3 --dirty 'all' \
          --ver-late 3 --require-total-dmas 3 >"$OUTDIR/N2.log" 2>&1; then
    echo "PASS  (N) ver=\$00: so' o status block por frame, zero views lidas"
    pass=$((pass+1))
  else
    echo "FAIL  (N) ver=\$00 nao parou o re-render:"
    sed 's/^/      /' "$OUTDIR/N2.log" | head -6; fail=$((fail+1))
  fi
  # SNAP_VALID = 0 is the same shape (sec. 5): the snapshot is not publishable,
  # so the frame is pads-and-IGR only.
  if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" --frames 3 --dirty 'all' \
          --no-snap 3 --require-total-dmas 3 >"$OUTDIR/N3.log" 2>&1; then
    echo "PASS  (N) SNAP_VALID=0: so' o status block por frame"
    pass=$((pass+1))
  else
    echo "FAIL  (N) SNAP_VALID=0:"; sed 's/^/      /' "$OUTDIR/N3.log" | head -6
    fail=$((fail+1))
  fi

  # -------------------------------------------------------------------------
  # (O) IGR: the two combos reach MCU_CMD ($2A00), once each, and the edge
  # latch ($04) means holding the combo does NOT fire again.  L+R is what keeps
  # them off the GB: sec. 9 maps neither shoulder button.
  # -------------------------------------------------------------------------
  for combo in "3030 80 L+R+Start+Select" "2070 81 L+R+Select+X"; do
    set -- $combo
    if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" --frames 4 --dirty 'none' \
            --pad "0;0x$1;0x$1;0" --require-mcu-cmd "0x$2" \
            >"$OUTDIR/O.$1.log" 2>&1; then
      echo "PASS  (O) IGR \$$1 ($3) -> MCU_CMD \$$2 uma unica vez (o combo e'"
      echo "          segurado por 2 frames e o latch de borda so' deixa 1 passar)"
      pass=$((pass+1))
    else
      echo "FAIL  (O) IGR \$$1:"; sed 's/^/      /' "$OUTDIR/O.$1.log" | head -6
      fail=$((fail+1))
    fi
  done

  # -------------------------------------------------------------------------
  # (B) carry-over: one window is NOT enough, and the backlog is what closes it
  # -------------------------------------------------------------------------
  if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
          --frames 1 --dirty 'all' --require-defer-first \
          >"$OUTDIR/B1.log" 2>&1; then
    echo "PASS  (B) frame 1 adia trabalho (carry-over existe)"
    pass=$((pass+1))
  else
    echo "FAIL  (B) frame 1:"; sed 's/^/      /' "$OUTDIR/B1.log"
    fail=$((fail+1))
  fi
  # ... and one frame short of convergence must still be pending: without this
  # a player that closed everything in frame 1 would pass (B) and (A) both.
  if [ "$NCONV" -gt 1 ]; then
    if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
            --frames $((NCONV - 1)) --dirty 'all;none' --require-converged \
            >"$OUTDIR/B2.log" 2>&1; then
      echo "FAIL  (B) fechou em $((NCONV - 1)) frames -- a medicao de convergencia mente"
      fail=$((fail+1))
    else
      echo "PASS  (B) $((NCONV - 1)) frames NAO fecham, $NCONV fecham"
      pass=$((pass+1))
    fi
  fi

  # -------------------------------------------------------------------------
  # (C) round-robin: every class advances under overload
  # -------------------------------------------------------------------------
  # ⚠ A MASCARA ACUMULADA "toda classe ja' avancou alguma vez" E' VACUO: o
  # refresh do boot liga todo bit dela nos dois primeiros frames e ela nunca
  # mais e' zerada, entao ela prova um EVENTO DE BOOT e nao o regime.  Uma
  # rotacao que starve uma classe para sempre a partir do frame 3 passa.
  #
  # A propriedade que o player afirma e' sobre o REGIME: com todas as classes
  # permanentemente sujas, TODA classe transfere mais que zero bytes em
  # QUALQUER janela de K frames, com K = !GBC_CLS_N.  A prova esta' no
  # GbcDrainEnd: a cabeca anda exatamente +1 e nao depende de mais nada, entao
  # em N frames consecutivos ela assume os N valores, e a classe que e' cabeca
  # e' varrida PRIMEIRO, com a janela A inteira na frente dela.
  #
  # `--require-fair K` mede exatamente isso -- a maior sequencia de frames
  # consecutivos em que uma classe nao moveu nada, depois de duas voltas de
  # aquecimento -- e imprime a tabela de bytes por classe.  600 frames para
  # que o regime tenha peso, e as cargas sao: TUDO sujo (o teto) e duas formas
  # realistas (mapas + um punhado de blocos de chr + OBJ + cor, todo frame),
  # que e' onde a starvation do par duplicado aparecia primeiro.
  C_FRAMES=600
  c_fair() { # <nome> <dirty>
    if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
            --frames "$C_FRAMES" --dirty "$2" --require-fair "$NCLS_N" \
            >"$OUTDIR/C.$1.log" 2>&1; then
      echo "PASS  (C) justica com --dirty '$2': $(grep -h '^justica' "$OUTDIR/C.$1.log")"
      sed -n '/^  classe/,/^$/p' "$OUTDIR/C.$1.log" | sed 's/^/      /'
      pass=$((pass+1))
    else
      echo "FAIL  (C) justica com --dirty '$2':"
      grep -hE '^(FAIL|  [0-9])' "$OUTDIR/C.$1.log" | sed 's/^/      /' | head -14
      fail=$((fail+1))
    fi
  }
  c_fair all 'all'
  c_fair mix1 'map:0-63+chr:0-15+obj:0-31+cram+oam'
  c_fair mix2 'map:0-63+chr:0-47+obj:0-15+cram+oam'

  # E o mutante: a regra que estava aqui antes -- "a cabeca da volta seguinte e'
  # a classe seguinte a' que abortou".  E' realimentacao, e com onze classes ela
  # fecha um ciclo limite: as cabecas possiveis viram {1,5,7} e duas classes
  # nunca mais sao cabeca.  Ele SAI 0 no gate antigo.
  if asar_ok; then
    RM="$OUTDIR/rotmut"
    rm -f "$RM.bin" "$RM.map"
    $PY - "$ASM" "$RM.asm" <<'PEOF'
import sys
src = open(sys.argv[1]).read()
old = """    lda.b $0D
    inc a
    cmp.b #!GBC_CLS_N
    bcc GbcDrainRotOk
    lda.b #$00
GbcDrainRotOk:
    sta.b $0D"""
new = """    lda.b $17
    bne GbcRotMut
    lda.b $0D
    inc a
    cmp.b #!GBC_CLS_N
    bcc GbcDrainRotOk
    lda.b #$00
GbcDrainRotOk:
    sta.b $0D
    bra GbcRotMutDone
GbcRotMut:
    lda.b $67
    sta.b $0D
GbcRotMutDone:"""
if old not in src:
    raise SystemExit("*** o alvo da mutacao da rotacao nao existe mais")
open(sys.argv[2], "w").write(src.replace(old, new, 1))
PEOF
    if [ ! -s "$RM.asm" ]; then
      echo "FAIL  (C mut) nao consegui montar o mutante da rotacao"
      fail=$((fail+1))
    else
      ( cd "$OUTDIR" && "$ASAR" -DGBC_HARNESS=1 --symbols=wla \
          --symbols-path=rotmut.sym rotmut.asm rotmut.bin ) >"$RM.log" 2>&1 &&
      $PY "$REPO_ROOT/snes/gbc/gen_map_asar.py" "$RM.sym" "$RM.bin" "$RM.map" \
          >>"$RM.log" 2>&1
      if [ ! -f "$RM.map" ]; then
        echo "FAIL  (C mut) nao montou:"; sed 's/^/      /' "$RM.log" | head -4
        fail=$((fail+1))
      elif $CLI --rom "$RM.bin" --map "$RM.map" --views "$VIEWS" \
                --frames "$C_FRAMES" --dirty 'all' --require-fair "$NCLS_N" \
                >"$RM.run.log" 2>&1; then
        echo "FAIL  (C mut) a rotacao realimentada passou -- a propriedade nao"
        echo "      esta' sendo provada"
        fail=$((fail+1))
      else
        echo "PASS  (C mut) rotacao realimentada derruba: $(grep -hm1 '^FAIL justica' "$RM.run.log" | cut -c1-80)"
        pass=$((pass+1))
      fi
    fi
  else
    echo "SKIP  (C mut) 1 mutante da rotacao: $asar_why"
    skip=$((skip+1))
  fi

  # -------------------------------------------------------------------------
  # (D) nothing dirty after convergence: only the status DMA survives
  # -------------------------------------------------------------------------
  if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
          --frames $((A_FRAMES + 2)) --dirty 'all;none' \
          --require-converged --require-last-frame-dmas 1 \
          >"$OUTDIR/D.log" 2>&1; then
    echo "PASS  (D) pos-convergencia: 1 DMA no ultimo frame (so' o status block)"
    pass=$((pass+1))
  else
    echo "FAIL  (D) frame ocioso:"; sed 's/^/      /' "$OUTDIR/D.log"
    fail=$((fail+1))
  fi

  # -------------------------------------------------------------------------
  # (I) bloco a bloco: depois de convergir, um conjunto ESCOLHIDO de blocos
  # sujos tem que produzir exatamente esses blocos na VRAM.  E' o teste do
  # mapeamento "sem permutacao nenhuma" do GbcClsTab -- e, nas classes de
  # mapa, do roteamento por LCDC.3 (BG) / LCDC.6 (WIN), que e' invisivel em
  # qualquer jogo que deixe os dois iguais.
  # 'map:0-3'/'map:4-7' are 4 blocks = 256 B; 'map:0-2'/'map:2-4' are 3 = 192.
  # That difference is not decoration: a run whose byte count is a multiple of
  # 256 hid the $58 aliasing bug this file was written to catch, so the
  # non-multiples are the cases that actually bite.
  # ⚡ wire $02: 'chr:8-15' is the $8800 block of bank 0, which goes to BOTH
  # chr bases; 'chr:16-23' is $9000 b0, which goes to ONE.  'map:0-3' and
  # 'map:32-35' are now rows of the SAME two classes ($9800's and $9C00's
  # halves), where wire $01 had LCDC pick which pair of views they landed in.
  for spec in 'chr:5' 'chr:0,47' 'chr:3-9' 'obj:0,31' 'map:0..63' \
              'chr:8-15' 'chr:16-23' 'chr:32-39' 'map:32-35' \
              'map:0-3' 'map:4-7' 'map:0-2' 'map:2-4+chr:11' 'oam+cram'; do
    if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
            --frames $((A_FRAMES + 1)) --dirty "all;none;none;none;none;none;$spec" \
            --require-blocks-match >"$OUTDIR/I.log" 2>&1; then
      echo "PASS  (I) blocos exatos para --dirty '$spec'"
      pass=$((pass+1))
    else
      echo "FAIL  (I) --dirty '$spec':"; grep -E '^FAIL' "$OUTDIR/I.log" | sed 's/^/      /'
      fail=$((fail+1))
    fi
  done

  # -------------------------------------------------------------------------
  # (P4B-DUP) ⚡ A PENDENCIA DE UM BLOCO $8800 SO' CAI DEPOIS DOS DOIS DMAs.
  #
  # O bloco $8800 de cada banco mora nas DUAS bases de chr, entao uma linha do
  # DIRTY_CHR vira duas transferencias.  Se o orcamento acabar entre elas, a
  # segunda TEM que continuar pendente e sair no frame seguinte -- limpar a
  # pendencia na primeira deixaria a base B com os tiles anteriores, e em
  # silencio, porque as duas copias sao byte-identicas sempre que nada mudou.
  # E' por isso que a duplicata e' uma CLASSE com backlog proprio.
  #
  # O caso exige as duas metades: as copias iguais no fim E pelo menos um par
  # partido em dois frames (senao o cenario nao exercitou o adiamento).  O
  # refresh do boot ja' e' esse cenario -- ele nao cabe num frame.
  # -------------------------------------------------------------------------
  if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
          --frames $((A_FRAMES + 2)) --dirty 'all;none' --require-dup-split \
          >"$OUTDIR/P4BDUP.log" 2>&1; then
    echo "PASS  (P4B-DUP) $(grep -hm1 '^duplicata' "$OUTDIR/P4BDUP.log")"
    pass=$((pass+1))
  else
    echo "FAIL  (P4B-DUP) a duplicata do bloco \$8800:"
    grep -hE '^(FAIL|duplicata)' "$OUTDIR/P4BDUP.log" | sed 's/^/      /' | head -5
    fail=$((fail+1))
  fi

  if asar_ok; then
    # O mutante: a classe duplicada compartilha o backlog da classe que ela
    # duplica, que e' exatamente "limpar a pendencia no primeiro DMA".
    MD="$OUTDIR/dupmut"
    rm -f "$MD.bin" "$MD.map"
    sed 's/^    dw \$003B, \$0077$/    dw $0021, $0077/' "$ASM" > "$MD.asm"
    if cmp -s "$ASM" "$MD.asm"; then
      echo "FAIL  (P4B-DUP mut) o alvo do sed nao existe mais em $(basename "$ASM")"
      fail=$((fail+1))
    else
      ( cd "$OUTDIR" && "$ASAR" -DGBC_HARNESS=1 --symbols=wla \
          --symbols-path=dupmut.sym dupmut.asm dupmut.bin ) >"$MD.log" 2>&1 &&
      $PY "$REPO_ROOT/snes/gbc/gen_map_asar.py" "$MD.sym" "$MD.bin" "$MD.map" \
          >>"$MD.log" 2>&1
      if [ ! -f "$MD.map" ]; then
        echo "FAIL  (P4B-DUP mut) nao montou:"; sed 's/^/      /' "$MD.log" | head -4
        fail=$((fail+1))
      elif $CLI --rom "$MD.bin" --map "$MD.map" --views "$VIEWS" \
                --frames $((A_FRAMES + 2)) --dirty 'all;none' --require-dup-split \
                >"$MD.run.log" 2>&1; then
        echo "FAIL  (P4B-DUP mut) a duplicata com backlog COMPARTILHADO passou --"
        echo "      a propriedade nao esta' sendo provada"
        fail=$((fail+1))
      else
        echo "PASS  (P4B-DUP mut) backlog compartilhado derruba: $(grep -hm1 '^FAIL duplicata' "$MD.run.log" | cut -c1-84)"
        pass=$((pass+1))
      fi
    fi
  else
    echo "SKIP  (P4B-DUP mut) 1 mutante: $asar_why"
    skip=$((skip+1))
  fi

  # -------------------------------------------------------------------------
  # (P4B-REGS) ⚡ OS SEIS REGISTRADORES DE BASE, PARA AS OITO COMBINACOES.
  #
  # LCDC.3 (qual mapa o fundo le'), LCDC.6 (qual a janela le') e LCDC.4 (qual
  # das duas bases de chr um indice de tile significa) sairam das views e
  # viraram $2107..$210B.  Um deles invertido desenha uma tela PLAUSIVEL com o
  # mapa ou a base errados, entao as oito combinacoes sao varridas -- e nao
  # so' a que a ROM do harness publica.
  # -------------------------------------------------------------------------
  for lcdc in 0x81 0x89 0x91 0x99 0xC1 0xC9 0xD1 0xD9; do
    $PY - "$VIEWS" "$OUTDIR/p4b_regs.views.bin" "$lcdc" <<'PEOF' \
         >"$OUTDIR/p4b_regs.mk.log" 2>&1
import struct, sys
d = bytearray(open(sys.argv[1], "rb").read())
assert d[:4] == b"GBVW", "nao e' um GBVW"
off = 8
while off + 8 <= len(d):
    tag = bytes(d[off:off+4]); ln = struct.unpack("<I", d[off+4:off+8])[0]
    if tag == b"STAT":
        d[off + 8 + 0x02] = int(sys.argv[3], 0)      # sec.5 +$02 = LCDC
        break
    off += 8 + ln
else:
    raise SystemExit("*** secao STAT nao encontrada")
open(sys.argv[2], "wb").write(bytes(d))
PEOF
    if $CLI --rom "$BIN" --map "$MAP" --views "$OUTDIR/p4b_regs.views.bin" \
            --frames 3 --dirty 'all;none' --dump-snes "$OUTDIR/p4b_regs.snst" \
            >"$OUTDIR/p4b_regs.log" 2>&1 &&
       $PY - "$OUTDIR/p4b_regs.snst" "$lcdc" <<'PEOF' >"$OUTDIR/p4b_regs.cmp.log" 2>&1
import struct, sys
d = open(sys.argv[1], "rb").read()
assert d[:4] == b"SNST"
off, sec = 8, {}
while off + 8 <= len(d):
    tag = d[off:off+4].decode("latin1")
    ln = struct.unpack("<I", d[off+4:off+8])[0]
    sec[tag] = d[off+8:off+8+ln]
    off += 8 + ln
regs, lcdc = sec["REGS"], int(sys.argv[2], 0)
b3, b4, b6 = (lcdc >> 3) & 1, (lcdc >> 4) & 1, (lcdc >> 6) & 1
want = {0x07: 0x44 if b6 else 0x40,   # BG1 map: the window's content
        0x08: 0x44 if b3 else 0x40,   # BG2 map: the background's content
        0x09: 0x4C if b6 else 0x48,   # BG3 map: the window's carpet
        0x0A: 0x4C if b3 else 0x48,   # BG4 map: the background's carpet
        0x0B: 0x22 if b4 else 0x33,   # BG1+BG2 chr base
        0x0C: 0x44}                   # BG3+BG4 chr base: tile 768 at $B000
bad = ["$21%02X = $%02X, esperado $%02X" % (a, regs[a], w)
       for a, w in sorted(want.items()) if regs[a] != w]
if bad:
    raise SystemExit("*** " + "; ".join(bad))
print("b3=%d b4=%d b6=%d -> %s" % (b3, b4, b6,
      " ".join("$21%02X=$%02X" % (a, w) for a, w in sorted(want.items()))))
PEOF
    then
      echo "PASS  (P4B-REGS LCDC=$lcdc) $(sed -n 1p "$OUTDIR/p4b_regs.cmp.log")"
      pass=$((pass+1))
    else
      echo "FAIL  (P4B-REGS LCDC=$lcdc):"
      sed 's/^/      /' "$OUTDIR/p4b_regs.cmp.log" 2>/dev/null | head -3
      grep -hE '^FAIL' "$OUTDIR/p4b_regs.log" 2>/dev/null | sed 's/^/      /' | head -2
      fail=$((fail+1))
    fi
  done

  # -------------------------------------------------------------------------
  # (P4B-VRAM mut) ⚡ O LAYOUT DE VRAM DO WIRE $02, POR MUTACAO.
  #
  # Cada um destes e' um erro que MONTA, roda e desenha: uma fatia de chr na
  # base errada, a duplicata esquecida, o mapa branco de volta por cima do
  # carpete, o par de nibbles de $210B trocado.  Nenhum deles aparece como
  # crash -- aparecem como tiles de outro banco, uma tela que nao branqueia ou
  # um fundo que troca de mapa sozinho.  O oraculo e' o snes_model.py, que e'
  # derivado do contrato e nao deste arquivo.
  # -------------------------------------------------------------------------
  if asar_ok; then
    p4b_vmut() { # <nome> <sed>
      local nm="$1" ex="$2" md="$OUTDIR/vmut"
      rm -f "$md.bin" "$md.map" "$md.snst"
      sed "$ex" "$ASM" > "$md.asm"
      if cmp -s "$ASM" "$md.asm"; then
        echo "FAIL  (P4B-VRAM mut) '$nm': o alvo do sed nao existe mais em $(basename "$ASM")"
        fail=$((fail+1)); return
      fi
      ( cd "$OUTDIR" && "$ASAR" -DGBC_HARNESS=1 --symbols=wla \
          --symbols-path=vmut.sym vmut.asm vmut.bin ) >"$md.log" 2>&1 &&
      $PY "$REPO_ROOT/snes/gbc/gen_map_asar.py" "$md.sym" "$md.bin" "$md.map" \
          >>"$md.log" 2>&1
      if [ ! -f "$md.map" ]; then
        echo "FAIL  (P4B-VRAM mut) '$nm' nao montou:"; sed 's/^/      /' "$md.log" | head -4
        fail=$((fail+1)); return
      fi
      $CLI --rom "$md.bin" --map "$md.map" --views "$VIEWS" \
           --frames "$A_FRAMES" --dirty 'all;none' --dump-snes "$md.snst" \
           >"$md.run.log" 2>&1
      GBC_VIEWSIM="$VIEWSIM" $PY "$OUTDIR/cmp_snes.py" "$md.snst" "$VIEWS" \
           --model-required >"$md.cmp.log" 2>&1
      case $? in
        0) echo "FAIL  (P4B-VRAM mut) '$nm' passou byte a byte -- a propriedade"
           echo "      nao esta' sendo provada"
           fail=$((fail+1));;
        77) echo "SKIP  (P4B-VRAM mut) '$nm': $(sed -n 1p "$md.cmp.log")"
            skip=$((skip+1));;
        *) echo "PASS  (P4B-VRAM mut) '$nm' derruba o byte a byte, como tem que ser"
           pass=$((pass+1));;
      esac
    }
    # A fatia do banco 1 da base A tomada 128 tiles adiante: o passo de banco
    # do wire $02 e' 256 tiles de view, nao 384 como era.
    p4b_vmut "fatia de chr do banco 1 deslocada" \
      's/^    dw 256, !GBC_BGCHR_A16+\$1800$/    dw 256, !GBC_BGCHR_A16+$2000/'
    # A duplicata nunca marcada: a base B fica com o $8800 anterior.
    p4b_vmut "duplicata do \$8800 nao marcada no fold" \
      's/^\( *\)ora.b \$3B$/\1lda.b #$00/'
    # O mapa branco de volta por cima do carpete do mapa 1, como no wire $01.
    p4b_vmut "mapa branco escrito por cima do carpete" \
      's/^\( *\)lda.w #\$5000        ; VRAM word \$5000 = byte \$A000$/\1lda.w #$4C00/'
    # $210B invertido por FRAME (o irmao do mutante por linha, la' em cima).
    p4b_vmut "\$210B invertido por frame" \
      's/^\( *\)lda.b #\$22          ; \$210B per frame: base A, VRAM \$4000/\1lda.b #$33/'
  else
    echo "SKIP  (P4B-VRAM mut) 4 mutantes do layout: $asar_why"
    skip=$((skip+4))
  fi

  # -------------------------------------------------------------------------
  # (E) SEQ inalterado = snapshot pulado: OAM/CGRAM NAO sao recopiados
  #     (contrato sec. 7).  Provado pelo par: com SEQ parado 1+1, com SEQ
  #     andando 3+3 -- um so' dos dois numeros nao prova nada.
  # -------------------------------------------------------------------------
  if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
          --frames 3 --dirty 'all' --seq-hold \
          --require-cgram-dmas 1 --require-oam-dmas 1 \
          >"$OUTDIR/E1.log" 2>&1; then
    echo "PASS  (E) SEQ parado: CGRAM/OAM copiados 1x em 3 frames"
    pass=$((pass+1))
  else
    echo "FAIL  (E) SEQ parado:"; sed 's/^/      /' "$OUTDIR/E1.log"
    fail=$((fail+1))
  fi
  if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
          --frames 3 --dirty 'all' \
          --require-cgram-dmas 3 --require-oam-dmas 3 \
          >"$OUTDIR/E2.log" 2>&1; then
    echo "PASS  (E) SEQ andando: CGRAM/OAM copiados 3x em 3 frames"
    pass=$((pass+1))
  else
    echo "FAIL  (E) SEQ andando:"; sed 's/^/      /' "$OUTDIR/E2.log"
    fail=$((fail+1))
  fi

  # -------------------------------------------------------------------------
  # (F) a guarda de V: dentro de [41,225) o letterbox ja' devolveu a tela e
  #     TODA transferencia tem que ser recusada (o modo de falha e' corrupcao
  #     silenciosa, nao glitch).
  # -------------------------------------------------------------------------
  for v in 41 100 224; do
    if $CLI --rom "$BIN" --map "$MAP" --views "$VIEWS" \
            --frames 3 --dirty 'all' --v "$v" \
            --require-total-dmas 0 --require-drops-min 3 \
            >"$OUTDIR/F$v.log" 2>&1; then
      echo "PASS  (F) V=$v: 0 DMAs, >=3 recusas da guarda"
      pass=$((pass+1))
    else
      echo "FAIL  (F) V=$v:"; sed 's/^/      /' "$OUTDIR/F$v.log"
      fail=$((fail+1))
    fi
  done


  # -------------------------------------------------------------------------
  # (P4-V13) A PHASE-3 CORE PLUS THE v1.4 PLAYER IS THE v1.3 PICTURE.
  #
  # !GBC_VER stays $01 across phase 4 BECAUSE of this: every field the phase
  # added lives in bytes sec. 5 had declared reserved, an old core publishes
  # them as $00, and $00 is exactly "no raster".  With DIRTY_MISC.RASTER clear,
  # LOG_N = 0 and COMPAT_RAW zeroed -- a status block a phase-3 bridge would
  # produce byte for byte -- the compiler has to arm ch4 + ch5 and NOTHING
  # else, and leave the same letterbox and window-1 tables the phase-2 player
  # left.  Both halves are checked: the $420C mask, and the two tables against
  # snes_model.py, which is the phase-2 ideal and has not moved.
  #
  # This is the rule written down in contract sec. 13.1: an ADDITIVE field in
  # reserved space that reads $00 on an old core does not bump the wire
  # version; a change of format, address or meaning does.
  # -------------------------------------------------------------------------
  gbc_views_patch "$OUTDIR/views_p3.bin" \
    'st[0x22] &= ~0x08; st[0x23] = 0; st[0x24] = 0; st[0x40:0x58] = bytes(24)' \
    >"$OUTDIR/p4v13.mk.log" 2>&1
  if [ ! -s "$OUTDIR/views_p3.bin" ]; then
    echo "FAIL  (P4-V13) montagem das views da fase 3:"
    sed 's/^/      /' "$OUTDIR/p4v13.mk.log"; fail=$((fail+1))
  else
    if $CLI --rom "$BIN" --map "$MAP" --views "$OUTDIR/views_p3.bin" --frames 8 \
            --dirty 'all;none' --require-420c 0x30 --require-hdma-budget \
            --dump-snes "$OUTDIR/p4v13.snst" >"$OUTDIR/p4v13.log" 2>&1; then
      echo "PASS  (P4-V13) nucleo da fase 3: $(grep -h '^orcamento' "$OUTDIR/p4v13.log")"
      pass=$((pass+1))
    else
      echo "FAIL  (P4-V13) nucleo da fase 3 + player v1.4:"
      grep -hE '^FAIL' "$OUTDIR/p4v13.log" | sed 's/^/      /' | head -4
      fail=$((fail+1))
    fi
    GBC_VIEWSIM="$VIEWSIM" $PY "$OUTDIR/cmp_snes.py" "$OUTDIR/p4v13.snst" \
        "$OUTDIR/views_p3.bin" --model-required >"$OUTDIR/p4v13.cmp.log" 2>&1
    case $? in
      0) echo "PASS  (P4-V13) letterbox + janela 1 iguais ao player da fase 2"
         pass=$((pass+1));;
      77) echo "SKIP  (P4-V13) vs o player ideal: $(sed -n 1p "$OUTDIR/p4v13.cmp.log")"
          skip=$((skip+1));;
      *) echo "FAIL  (P4-V13) as tabelas nao sao as da fase 2:"
         sed 's/^/      /' "$OUTDIR/p4v13.cmp.log" | head -8; fail=$((fail+1));;
    esac
  fi

  # -------------------------------------------------------------------------
  # (P4) THE RASTER GATE: the mid-frame log, compiled into the six HDMA tables.
  #
  # Every case is a {status block, log, CRAM} the phase-4 golden published
  # together with the tables IT compiled out of them.  The player has to leave
  # exactly those bytes in WRAM, arm exactly those channels in $420C and count
  # exactly what the golden counted -- with nothing in between but its own
  # assembly: the log goes IN by DMA out of the view and comes back OUT of the
  # HDMA set the prologue published, found through the channel's own $43x2.
  #
  # Two sources, one format.  The twelve VERSIONED fixtures are the contract
  # (two of them are the acid2 ROMs' real logs).  The SYNTHETIC ones are the
  # corners of the TABLE SPEC those twelve do not happen to reach -- an
  # isolated line, a run past 127, a colour that has to wait, a log past the
  # 512 the bridge keeps -- and hdma.py compiles them here, exactly as it
  # compiled the others.
  #
  # The cases carry the RAW CRAM, not the CGRAM view, so views.py (the same
  # sec. 4.4 model the phase-2 gate is measured against) builds the view from
  # it.  That is also why this block needs viewsim.
  # -------------------------------------------------------------------------
  p4_run() { # <nome> <dir>
    local fx="$1" d="$2" out="$OUTDIR/p4_$1"
    if ! GBC_VIEWSIM="$VIEWSIM" $PY "$OUTDIR/mkfixture.py" "$d" "$out.views.bin" \
           >"$out.mk.log" 2>&1; then
      echo "FAIL  (P4 $fx) montagem das views:"; sed 's/^/      /' "$out.mk.log"
      fail=$((fail+1)); return
    fi
    if ! $CLI --rom "$BIN" --map "$MAP" --views "$out.views.bin" \
              --frames 8 --dirty 'all;none' --dump-snes "$out.snst" \
              >"$out.log" 2>&1; then
      echo "FAIL  (P4 $fx) o player abortou:"
      grep -hE '^(FAIL|m65816)' "$out.log" | sed 's/^/      /' | head -5
      fail=$((fail+1)); return
    fi
    if $PY "$OUTDIR/cmp_p4.py" "$out.snst" "$d" >"$out.cmp.log" 2>&1; then
      echo "PASS  (P4 $fx) $(sed -n 1p "$out.cmp.log")"
      pass=$((pass+1))
    else
      echo "FAIL  (P4 $fx):"; sed 's/^/      /' "$out.cmp.log" | head -12
      fail=$((fail+1))
    fi
  }

  if [ ! -f "$FIXTURES/manifest.json" ] || [ ! -f "$VIEWSIM/hdma.py" ]; then
    if [ "$FIX_REQUIRED" != "0" ]; then
      echo "FAIL  (P4) fixtures/golden ausentes ($FIXTURES, $VIEWSIM)"
      echo "      GBC_FIXTURES_REQUIRED esta' setado, entao nao compilar o log e' falha."
      fail=$((fail+1))
    else
      echo "SKIP  (P4) raster ($p4_planned casos nao checados): fixtures da fase 4"
      echo "      ausentes em $FIXTURES -- nao fazem parte deste repositorio"
      skip=$((skip+p4_planned))
    fi
  else
    for fx in $($PY - "$FIXTURES/manifest.json" <<'PEOF'
import json, sys
print(" ".join(json.load(open(sys.argv[1]))["fixtures"]))
PEOF
    ); do
      p4_run "$fx" "$FIXTURES/$fx"
    done

    SYNDIR="$OUTDIR/syn"
    mkdir -p "$SYNDIR"
    for c in $(GBC_VIEWSIM="$VIEWSIM" $PY "$OUTDIR/mkcase.py" --list); do
      if GBC_VIEWSIM="$VIEWSIM" $PY "$OUTDIR/mkcase.py" "$c" "$SYNDIR" \
           >"$OUTDIR/syn.$c.log" 2>&1; then
        p4_run "$c" "$SYNDIR/$c"
      else
        echo "FAIL  (P4 $c) o golden nao compilou o caso sintetico:"
        sed 's/^/      /' "$OUTDIR/syn.$c.log" | head -6
        fail=$((fail+1))
      fi
    done

    # --- (P4-CG) THE COLOUR CHANNEL AND THE CGRAM DMA CANNOT SHARE A LINE.
    #
    # An armed colour channel writes $2121/$2122 in the hblank of EVERY line it
    # is armed for, rows 0..40 included -- which is the letterbox tail the
    # player drains in.  A general DMA to CGRAM sets $2121 once and then
    # streams $2122, so an HDMA $2121 in the middle of it walks the CGRAM
    # pointer and 512 bytes of colour land in the wrong entries, silently.
    #
    # Four runs, one property: with the transfer sitting in the TAIL (V=20) the
    # CGRAM DMA must survive when no colour channel is up and be refused when
    # one is; in TRUE vblank (V=230) neither case may lose it, or the rule
    # would be costing bandwidth it does not need to.  The dirty spec releases
    # the screen first and only then re-dirties CGRAM, because before the
    # release $420C is 0 and nothing is on the bus at all.  ⚡ wire $02 pushed
    # the release out (nine classes, and 16 KB of chr instead of 12), so the
    # quiet run is eight frames and the four CGRAM ones come after it -- the
    # expected counts are unchanged: one before the release plus four after.
    p4_cgram() { # <nome> <caso> <v> <esperado>
      if $CLI --rom "$BIN" --map "$MAP" --views "$OUTDIR/p4_$2.views.bin" \
              --frames 12 \
              --dirty 'all;none;none;none;none;none;none;none;cram' --v "$3" \
              --require-cgram-dmas "$4" >"$OUTDIR/p4cg.$2.$3.log" 2>&1; then
        echo "PASS  (P4-CG) $1"
        pass=$((pass+1))
      else
        echo "FAIL  (P4-CG) $1:"
        grep -hE '^(FAIL|kinds)' "$OUTDIR/p4cg.$2.$3.log" | sed 's/^/      /' | head -4
        fail=$((fail+1))
      fi
    }
    p4_cgram "sem canal de cor, V=20: os 5 DMAs de CGRAM passam" p4-empty 20 5
    p4_cgram "com canal de cor, V=20: so' o de antes do arme passa" p4-cgb-colour 20 1
    p4_cgram "sem canal de cor, V=230: 5 DMAs" p4-empty 230 5
    p4_cgram "com canal de cor, V=230: os mesmos 5, a regra nao cobra vblank" \
             p4-cgb-colour 230 5

    # --- (P4-CG) A BORDA DO VBLANK.  "V >= 225" nao e' a regra: 512 bytes sao
    # ~3 scanlines, entao um DMA disparado em V = 259..261 ainda esta' no
    # barramento em V = 0, que e' exatamente onde a HDMA reinicializa e todo
    # canal de cor armado faz a PRIMEIRA transferencia do hold de letterbox --
    # $2121 inclusive.  O bloco tem que CABER no que sobra do vblank, e o teto
    # e' o termo de vblank sozinho: a capacidade que GbcCapacity devolve soma a
    # cauda de 40 linhas ($71, ~5,7 KB-eq com quatro canais de cor), e e' a
    # cauda que esta' proibida aqui -- comparar com ela aceitaria V = 261.
    #
    # (261 - V) * !GBC_BPLVBL >= 512 + !GBC_DMASTART + !GBC_CGFITSLACK poe a
    # fronteira em V = 256 (5 x 170 = 850 >= 809; em 257 sobram 680).  So' as
    # linhas DEPOIS da lida contam (o latch pode cair no ultimo ponto dela) e a
    # CPU entre o latch e o $420B tem folga propria: a fronteira antiga (258)
    # dava S9 no P5-VIRQ p4-cgb-colour com a CPU x1,3 no proprio player $02
    # (advisor C6-PLAYER).  O controle negativo continua sendo o par sem canal
    # de cor, que nao pode perder nada em V nenhum.
    p4_cgram "com canal de cor, V=255: cabe no vblank, os 5 passam" p4-cgb-colour 255 5
    p4_cgram "com canal de cor, V=256: o ULTIMO que cabe (850 eq de 809)" \
             p4-cgb-colour 256 5
    p4_cgram "com canal de cor, V=257: 680 eq nao chegam -- recusado" p4-cgb-colour 257 1
    p4_cgram "com canal de cor, V=258: recusado" p4-cgb-colour 258 1
    p4_cgram "com canal de cor, V=259: recusado" p4-cgb-colour 259 1
    p4_cgram "com canal de cor, V=260: recusado" p4-cgb-colour 260 1
    p4_cgram "com canal de cor, V=261: recusado" p4-cgb-colour 261 1
    p4_cgram "sem canal de cor, V=261: os 5 passam (a regra nao cobra quem nao colide)" \
             p4-empty 261 5


    # --- MUTANTE da regra de borda: um player que volta a testar SO' o V de
    #     inicio aceita o bloco em V=260 e ele ainda estaria no barramento na
    #     init da HDMA.  Neutraliza a leitura da capacidade do vblank (o
    #     produto que o multiplicador devolve) por um teto infinito, que e'
    #     exatamente "a regra antiga".
    if asar_ok; then
      MCG="$OUTDIR/p4cgmut"
      rm -f "$MCG.bin" "$MCG.map"
      sed 's/^\( *\)lda.w \$4216         ; byte-equivalents left in THIS vblank/\1lda.w #$FFFF/' \
        "$ASM" > "$MCG.asm"
      if cmp -s "$ASM" "$MCG.asm"; then
        echo "FAIL  (P4-CG mut) o alvo do sed nao existe mais em $(basename "$ASM")"
        fail=$((fail+1))
      else
        ( cd "$OUTDIR" && "$ASAR" -DGBC_HARNESS=1 --symbols=wla \
            --symbols-path=p4cgmut.sym p4cgmut.asm p4cgmut.bin ) >"$MCG.log" 2>&1 &&
        $PY "$REPO_ROOT/snes/gbc/gen_map_asar.py" "$MCG.sym" "$MCG.bin" "$MCG.map" \
            >>"$MCG.log" 2>&1
        if [ ! -f "$MCG.map" ]; then
          echo "FAIL  (P4-CG mut) nao montou:"; sed 's/^/      /' "$MCG.log" | head -4
          fail=$((fail+1))
        elif $CLI --rom "$MCG.bin" --map "$MCG.map" \
                  --views "$OUTDIR/p4_p4-cgb-colour.views.bin" --frames 8 \
                  --dirty 'all;none;none;none;cram' --v 260 \
                  --require-cgram-dmas 1 >"$MCG.run.log" 2>&1; then
          echo "FAIL  (P4-CG mut) o player que so' testa o V de inicio recusou em"
          echo "      V=260 mesmo assim -- o caso de borda nao esta' provando nada"
          fail=$((fail+1))
        else
          echo "PASS  (P4-CG mut) so' o teste do V de inicio aceita em V=260, como tem que ser"
          pass=$((pass+1))
        fi
      fi
    else
      echo "SKIP  (P4-CG mut) 1 caso: $asar_why"
      skip=$((skip+1))
    fi

    # --- (P4-NMI) A COMPILACAO RODA NO MAIN LOOP E A NMI A INTERROMPE.
    #
    # E' a decisao estrutural da fase 4, e GbcFrameOnce -- corpo e depois
    # compilacao, um atras do outro -- e' justamente a forma que nao consegue
    # testa-la.  --interleave roda GbcRasterRun em fatias de N instrucoes e
    # injeta um corpo INTEIRO entre fatias, com as views mexidas em volta de
    # cada injecao: assim "o corpo recopiou o log que a compilacao esta' lendo"
    # aparece como BYTES QUE MUDARAM e nao como uma afirmacao sobre o fonte.
    # O que e' exigido de cada injecao esta' em il_inject (gbc_render_cli.c);
    # no fim, as tabelas ainda tem que bater byte a byte com o golden, que e'
    # o que diz que as N interrupcoes nao mudaram o RESULTADO.
    #
    # N varre numeros primos para que os pontos de corte caiam em toda parte
    # das cinco passadas em vez de num ponto fixo de cada uma.
    p4_nmi() { # <caso> <N> <frames>
      local c="$1" n="$2" fr="$3" out="$OUTDIR/p4nmi.$1.$2"
      if ! $CLI --rom "$BIN" --map "$MAP" --views "$OUTDIR/p4_$c.views.bin" \
                --frames "$fr" --dirty 'all;none' --interleave "$n" \
                --require-wram-quiet --dump-snes "$out.snst" >"$out.log" 2>&1; then
        echo "FAIL  (P4-NMI $c N=$n):"
        grep -hE '^(FAIL|m65816)' "$out.log" | sed 's/^/      /' | head -6
        fail=$((fail+1)); return
      fi
      local d="$FIXTURES/$c"
      [ -d "$d" ] || d="$SYNDIR/$c"
      if $PY "$OUTDIR/cmp_p4.py" "$out.snst" "$d" >"$out.cmp.log" 2>&1; then
        echo "PASS  (P4-NMI $c N=$n) $(grep -h '^interleave' "$out.log" |
              sed 's/^interleave: //'), tabelas identicas ao golden"
        pass=$((pass+1))
      else
        echo "FAIL  (P4-NMI $c N=$n) as tabelas mudaram com a NMI no meio:"
        sed 's/^/      /' "$out.cmp.log" | head -8
        fail=$((fail+1))
      fi
    }
    p4_nmi p4-parallax    97 6
    p4_nmi p4-parallax   211 6
    p4_nmi p4-parallax   401 6
    p4_nmi p4-hud-wy     211 6      # $73 b1: o par da JANELA na HDMA
    p4_nmi p4-cgb-colour 313 6      # quatro canais de cor + a copia da CGRAM
    p4_nmi dmg-acid2      97 6      # ROM real, compat, os seis canais
    p4_nmi p4-144-lines 2003 6      # compilacao de varios frames
    # ⚡ wire $02: o canal de LCDC sozinho, e o caso de pressao em que ele
    # toma o ch3 do par da janela (o $73 ganhou um bit por causa disso).
    p4_nmi p4b-lcdc-with-scroll   211 6
    p4_nmi p4b-lcdc-evicts-carpet 113 6

    # Os tres mutantes que o corpo/compilador so' separam POR ESSA ESTRUTURA.
    # Sem a injecao todos os tres passam em todos os outros casos do gate.
    if asar_ok; then
      p4_nmi_mutant() { # <nome> <sed> <caso> <N>
        local nm="$1" ex="$2" c="$3" n="$4"
        local ma="$OUTDIR/p4nmut.asm" mb="$OUTDIR/p4nmut.bin" mm="$OUTDIR/p4nmut.map"
        rm -f "$mm" "$mb"
        sed "$ex" "$ASM" > "$ma"
        if cmp -s "$ASM" "$ma"; then
          echo "FAIL  (P4-NMI mut) '$nm': o alvo do sed nao existe mais em $(basename "$ASM")"
          fail=$((fail+1)); return
        fi
        ( cd "$OUTDIR" && "$ASAR" -DGBC_HARNESS=1 --symbols=wla \
            --symbols-path=p4nmut.sym p4nmut.asm p4nmut.bin ) >"$OUTDIR/p4nmut.log" 2>&1 &&
        $PY "$REPO_ROOT/snes/gbc/gen_map_asar.py" "$OUTDIR/p4nmut.sym" "$mb" "$mm" \
