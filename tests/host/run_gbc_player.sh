#!/usr/bin/env python3
"""Deterministic synthetic GBVW, for a clone without gbc/tests/viewsim.

It is NOT a golden: the byte-exact gate against snes_model.py needs the real
model.  What it is good for is exercising the transfer engine -- every block
distinguishable from every other, so a swapped source or destination shows up
as a diff instead of as two identical zeros.
"""
import struct, sys

SECS = [("BGCH", 12288), ("OBCH", 16384), ("MC0_", 2048), ("MC1_", 2048),
        ("MK0_", 2048), ("MK1_", 2048), ("CGRM", 512), ("STAT", 256),
        ("OAMV", 544)]

def xs32(s):
    s ^= (s << 13) & 0xFFFFFFFF; s ^= s >> 17; s ^= (s << 5) & 0xFFFFFFFF
    return s

def body(tag, n, seed):
    out = bytearray(n)
    s = seed
    for i in range(n):
        s = xs32(s)
        out[i] = (s ^ (i * 7) ^ (i >> 8)) & 0xFF
    return bytes(out)

def status():
    st = bytearray(256)
    st[0x00] = WIRE_VER                  # ver, from the .asm (!GBC_VER)
    st[0x01] = 0x01 | 0x02 | 0x80        # LCD_ON | CGB_MODE | SNAP_VALID
    st[0x02] = 0x91                      # LCDC: BG on, LCD on, tiles $8000
    st[0x03] = 12                        # SCX
    st[0x04] = 5                         # SCY
    st[0x05] = 7                         # WX
    st[0x06] = 64                        # WY
    st[0x07] = 0xE4                      # BGP
    return bytes(st)

def main(path):
    out = b"GBVW" + struct.pack("<I", 1)
    for i, (tag, n) in enumerate(SECS):
        p = status() if tag == "STAT" else body(tag, n, 0xA53C1700 + i * 0x9E37)
        if tag == "OAMV":
            p = bytearray(p)
            p[512:544] = bytes(32)       # high table = 32 x $00 (sec. 4.5)
            p = bytes(p)
        if tag == "CGRM":
            p = bytearray(p)
            p[0:2] = b"\x00\x00"         # CGRAM[0]  = $0000 (sec. 4.4)
            p[196:198] = b"\xff\x7f"     # CGRAM[98] = $7FFF
            for k in range(1, 256):      # BGR555: bit 15 is always 0
                p[k * 2 + 1] &= 0x7F
            p[1] = 0
            p = bytes(p)
        out += tag.encode("latin1") + struct.pack("<I", n) + p
    open(path, "wb").write(out)
    print("GBVW sintetico: %s (%d B)" % (path, len(out)))

WIRE_VER = int(sys.argv[2], 0) if len(sys.argv) > 2 else 0x02
main(sys.argv[1])
MKEOF

