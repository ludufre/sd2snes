    out, off = {}, 8
    while off + 8 <= len(d):
        tag = d[off:off + 4].decode("latin1")
        ln = struct.unpack("<I", d[off + 4:off + 8])[0]
        out[tag] = d[off + 8:off + 8 + ln]
        off += 8 + ln
    return out


def main(snst_path, fixdir):
    s = sections(snst_path, b"SNST")
    man = json.load(open(os.path.join(fixdir, "manifest.json")))
    # GbcHarnessMap only ever APPENDS words, so read as many as are there.
    hm = struct.unpack("<%dH" % (len(s["HMAP"]) // 2), s["HMAP"])
    seta, setb = 0x7e0000 | hm[2], 0x7e0000 | hm[3]
    setlen = setb - seta
    hdma, cpur, dmar, rctr = s["HDMA"], s["CPUR"], s["DMAR"], s["RCTR"]
    bad = []

    got420c = cpur[0x0C]
    if got420c != man["r420c"]:
        bad.append("$420C = $%02X, o golden diz $%02X (canais a mais/menos)"
                   % (got420c, man["r420c"]))

    # Which half of the dumped HDMA blob a table address falls in.
    def table_at(a1b, a1t, n):
        base = (a1b << 16) | a1t
        for half, lo in ((0, seta), (setlen, setb)):
            if lo <= base < lo + setlen:
                off = half + (base - lo)
                return hdma[off:off + n]
        return None

    for nstr, ch in sorted(man["channels"].items(), key=lambda kv: int(kv[0])):
        n = int(nstr)
        want = open(os.path.join(fixdir, ch["file"]), "rb").read()
        if not (got420c >> n) & 1:
            bad.append("ch%d devia estar armado (%s, %s) e $420C nao o tem"
                       % (n, ch["role"], BBAD_NAME.get(ch["bbad"], "?")))
            continue
        r = dmar[n * 0x10:n * 0x10 + 5]
        if r[1] != ch["bbad"]:
            bad.append("ch%d: $43%d1 = $%02X, o golden diz $%02X (%s)"
                       % (n, n, r[1], ch["bbad"], ch["role"]))
        if (r[0] & 0x07) != ch["mode"]:
            bad.append("ch%d: $43%d0 = $%02X, modo %d, o golden diz %d"
                       % (n, n, r[0], r[0] & 7, ch["mode"]))
        got = table_at(r[4], r[2] | (r[3] << 8), len(want))
        if got is None:
            bad.append("ch%d aponta para $%02X:%04X, fora dos dois conjuntos"
                       % (n, r[4], r[2] | (r[3] << 8)))
            continue
        if got != want:
            k = next(i for i in range(min(len(got), len(want)))
                     if got[i] != want[i])
            bad.append("ch%d (%s, %d B): byte %d = $%02X, o golden diz $%02X\n"
                       "      player: %s\n      golden: %s"
                       % (n, ch["role"], len(want), k, got[k], want[k],
                          " ".join("%02X" % b for b in got[:16]),
                          " ".join("%02X" % b for b in want[:16])))

    for n in range(6):
        if str(n) in man["channels"]:
            continue
        if (got420c >> n) & 1:
            bad.append("ch%d esta' armado e o golden nao lhe deu tabela" % n)

    want_ctr = man["counters"]
    for i, name in enumerate(RCTR):
        if name not in want_ctr:
            continue
        got = rctr[i * 2] | (rctr[i * 2 + 1] << 8)
        if got != want_ctr[name]:
            bad.append("contador %s = %d, o golden diz %d"
                       % (name, got, want_ctr[name]))
    gotn = rctr[20] | (rctr[21] << 8)
    if gotn != man["log_n"]:
        bad.append("o player compilou %d entradas, a fixture tem %d"
                   % (gotn, man["log_n"]))

    if bad:
        print("FAIL %s" % man["name"])
        for b in bad:
            print("  " + b)
        raise SystemExit(1)
    print("$420C = $%02X, %d canal(is), %d B de tabela, contadores OK"
          % (got420c, len(man["channels"]), man["total_table_bytes"]))


main(sys.argv[1], sys.argv[2])

