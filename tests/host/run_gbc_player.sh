  # -------------------------------------------------------------------------
  # (MBX) THE COUNTER MAILBOX (contract sec. 3/10): the player copies FRAMES,
  #     DEFER, DROPS, READY and REGSLATE into $EF0010-$EF0019 once per frame
  #     so the MCU can read them in GBDG +20..+29 -- SNES WRAM is invisible to
  #     USB on this core.  The CLI plays the bridge's half (same lo/hi pairing
  #     rule as gbc_bridge.v) and checks, for EVERY frame of EVERY run above,
  #     that the words published after CONSUMED equal the WRAM counters.  These cases add
  #     the part an always-on check cannot: that the words are not trivially
  #     zero (each counter is driven non-zero by its own scenario and the
  #     report must show it), and three mutants that must fail.
  # -------------------------------------------------------------------------
  mbxval() { sed -n "s/^mailbox:.* $2=\$\([0-9A-F]*\).*/\1/p" "$1" | head -1; }
  mbx_case() { # <tag> <expect: "NAME>0 ..."> <log> [args...]
    local tag="$1" want="$2" l="$3" bad="" nm v; shift 3
    if GBC_MBX_REPORT=1 $CLI --rom "$BIN" --map "$MAP" "$@" >"$l" 2>&1; then
      for nm in $want; do
        v=$(mbxval "$l" "$nm")
        [ -n "$v" ] && [ $((16#$v)) -gt 0 ] || bad="$bad $nm=${v:-?}"
      done
      if [ -z "$bad" ]; then
        echo "PASS  (MBX $tag) $(grep -h '^mailbox:' "$l" | cut -c10-)"
        pass=$((pass+1))
      else
        echo "FAIL  (MBX $tag) publicado zero onde o cenario move o contador:$bad"
        fail=$((fail+1))
      fi
    else
      echo "FAIL  (MBX $tag):"; grep -hE '^(FAIL|m65816)' "$l" | sed 's/^/      /' | head -4
      fail=$((fail+1))
    fi
  }
