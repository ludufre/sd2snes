d = bytearray(open(sys.argv[1], "rb").read())
if bytes(d[0x7F80:0x7F85]) != b"GBCF\x01":
    sys.exit("%s: no GBCF v1 block at $7F80" % sys.argv[1])
d[0x7F85] = int(sys.argv[3], 0)
open(sys.argv[2], "wb").write(d)
GBCFEOF
