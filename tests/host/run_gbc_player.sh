    beq GbcNmiNoDefer" \
      "    ; Every counter of the frame has moved by now (DEFER is the last, above).
    jsr GbcMbxPublish
" "    ; (mutant: published before DEFER)
"
    mbx_mutant "byte alto antes do baixo" \
      "    jsr GbcEfPut        ; sep #\$20 inside: the low byte
