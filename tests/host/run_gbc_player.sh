  # -------------------------------------------------------------------------
  # (SEQ) A SCENE CHANGE, AND THE TWO HDMA SETS AFTER IT.
  #
  # The HDMA alternates between set A and set B every frame, so once a scene
  # settles the two sets must carry the SAME tables -- any difference is a
  # picture that flips between two rasters every frame on the console.  And a
  # scene whose log has no palette write owes no colour channel at all.
  # Every other case here serves ONE (snapshot, log) pair for the whole run,
  # which cannot reach either property: both bugs below live in the frames
  # AFTER a raster scene, and --views-at swaps the published scene mid-run.
  #   * a colour log followed by one without palette writes: the "spare got an
  #     entry" flags of the colour compile outlived it and re-armed its stale
  #     colour tables on every later frame (Dragon Warrior III: the title's
  #     palette fade repainting the menu blue/lilac, the dream red/cyan);
  #   * the same with a DEFERRED frame (SNAP_VALID = 0) at the transition: the
  #     rebuild debt was a COUNT, the deferred frame still flipped the sets, so
  #     both owed compiles landed in one set and the other kept the previous
  #     scene for good.  With a deferral every OTHER frame, only a per-set debt
  #     whose claim waits for the set that owes converges.
  # -------------------------------------------------------------------------
  #   * a colour channel that LEAVES the bus leaves its last writes in CGRAM,
  #     and CGRAM is only re-sent when the snapshot's CRAM moves: the frames in
  #     which the previous scene's colour tables were still on the bus (compile
  #     latency, a deferral) stay on a static screen for good.  Hence the third
  #     check, the PICTURE: --require-cgram-view plays the armed colour channels
  #     into a persistent CGRAM after every frame and wants the CGRAM the
  #     display ends on to equal the view -- with CRAM dirty ONLY on the swap
  #     frame, the hardest case (Harvest Moon 3: sprites white, text yellow);
  #   * with a log that re-owes both sets on every arm and a deferral every
  #     other frame, every arm lands at the same parity: only the prologue's
  #     re-arm of the set still owed converges (Dragon Warrior III's dream);
  #   * and a quiet scene has to bring the compiler back to rest
  #     (--require-raster-idle): a debt never paid still draws the right
  #     picture, it just recompiles every frame for ever.
  # Every case also runs under --clock (the free-running main loop, whose
  # compile latency is the real one), where --flags0 does not apply.
  # -------------------------------------------------------------------------
  SEQFX="$FIXTURES/../fixtures_seq"
  SEQD='all;none;none;none;none;none;none;none;all;none'
  SEQCKD="all$(printf ';none%.0s' $(seq 1 18));all;none"
  SEQ1='0x83;0x83;0x83;0x83;0x83;0x83;0x83;0x83;0x83;0x03;0x83'
  SEQALT="0x83$(printf ';0x83%.0s' $(seq 1 8));0x03$(printf ';0x83;0x03%.0s' $(seq 1 7))"
  # seq_run <views 1..> <views after> <flags0 | "clock"> <quiet 0|1> [<bin> <map>]
  seq_run() {
    local v0="$1" v1="$2" fl="$3" q="$4" b="${5:-$BIN}" m="${6:-$MAP}" md
    md="--frames 24 --views-at 9:$v1 --dirty $SEQD"
    [ "$fl" = clock ] && { md="--clock --frames 60 --views-at 20:$v1 --dirty $SEQCKD"; fl=; }
    $CLI --rom "$b" --map "$m" --views "$v0" $md ${fl:+--flags0 "$fl"} \
         --require-sets-equal --require-no-colour --require-cgram-view \
         $([ "$q" = 1 ] && echo --require-raster-idle)
  }
  if [ ! -f "$OUTDIR/p4_p4-cgb-colour.views.bin" ] || [ ! -f "$OUTDIR/p4_p4-window-static.views.bin" ]; then
    if [ "$FIX_REQUIRED" != "0" ]; then
      echo "FAIL  (SEQ) views da fase 4 ausentes"; fail=$((fail+1))
    else
      echo "SKIP  (SEQ) 16 casos + 5 mutantes: views da fase 4 ausentes"; skip=$((skip+21))
    fi
  else
    SEQC="$OUTDIR/p4_p4-cgb-colour.views.bin"; SEQS="$OUTDIR/p4_p4-window-static.views.bin"
    SEQ1B=$(echo "$SEQ1" | sed 's/0x83/0x8b/g;s/0x03/0x0b/g')
    SEQALTB=$(echo "$SEQALT" | sed 's/0x83/0x8b/g;s/0x03/0x0b/g')
    # <name>|<views before>|<views after>|<flags0 or clock>|<quiet>.  The Dragon
    # Warrior III and Harvest Moon 3 pairs are the games' own (snapshot, log)
    # out of SameBoy (gbc/tests/viewsim/fixtures_seq/mk_seq_views.py):
    # dw3-fade-* is the palette fade (128 BCPD/OCPD writes over lines 10..106),
    # dw3-menu an EMPTY log, dw3-dream a SCX/SCY/LCDC split with no palette;
    # hm3-fade-ok the "Everything OK?" fade (98 writes) and hm3-farm an empty log;
    # dkc-fade-logo a 128-write fade and dkc-lang the language selector (empty
    # log), which the console showed almost black.
    seq_n=0
    while IFS='|' read -r nm a b fl q; do
      [ -n "$nm" ] || continue
      case "$a" in SEQC) a="$SEQC";; *) a="$SEQFX/$a.views.bin";; esac
      case "$b" in SEQS) b="$SEQS";; *) b="$SEQFX/$b.views.bin";; esac
      eval "fl=\"$fl\""
      if [ ! -f "$a" ] || [ ! -f "$b" ]; then
        if [ "$FIX_REQUIRED" != "0" ]; then
          echo "FAIL  (SEQ) $nm: fixture ausente em $SEQFX"; fail=$((fail+1))
        else
          echo "SKIP  (SEQ) $nm: fixture ausente em $SEQFX"; skip=$((skip+1))
        fi
        continue
      fi
      if seq_run "$a" "$b" "$fl" "$q" >"$OUTDIR/seq.log" 2>&1; then
        echo "PASS  (SEQ) $nm: conjuntos iguais, sem cor velha, CGRAM da tela = view$([ "$q" = 1 ] && echo ', compilador em repouso')"
        pass=$((pass+1))
      else
        echo "FAIL  (SEQ) $nm:"; grep -h '^FAIL' "$OUTDIR/seq.log" | sed 's/^/      /' | head -3
        fail=$((fail+1))
      fi
    done <<'SEQCASES'
cor -> quieto|SEQC|SEQS||1
cor -> quieto, 1 frame adiado|SEQC|SEQS|$SEQ1|1
cor -> quieto, adiado frame sim frame nao|SEQC|SEQS|$SEQALT|1
cor -> quieto, --clock|SEQC|SEQS|clock|1
DW3 fade do titulo -> menu|dw3-fade-title|dw3-menu||1
DW3 fade do titulo -> menu, 1 frame adiado|dw3-fade-title|dw3-menu|$SEQ1B|1
DW3 fade do titulo -> menu, --clock|dw3-fade-title|dw3-menu|clock|1
DW3 fade -> sonho|dw3-fade-dream|dw3-dream||0
DW3 fade -> sonho, adiado frame sim frame nao|dw3-fade-dream|dw3-dream|$SEQALTB|0
DW3 fade -> sonho, --clock|dw3-fade-dream|dw3-dream|clock|0
HM3 fade -> fazenda|hm3-fade-ok|hm3-farm||1
HM3 fade -> fazenda, 1 frame adiado|hm3-fade-ok|hm3-farm|$SEQ1|1
HM3 fade -> fazenda, adiado frame sim frame nao|hm3-fade-ok|hm3-farm|$SEQALT|1
HM3 fade -> fazenda, --clock|hm3-fade-ok|hm3-farm|clock|1
DKC fade do logo -> seletor de idioma|dkc-fade-logo|dkc-lang||1
DKC fade do logo -> seletor de idioma, --clock|dkc-fade-logo|dkc-lang|clock|1
SEQCASES
    if asar_ok; then
      seq_mut() { # <nome> <sed> <views before> <views after> <flags0|clock> <quiet>
        local md="$OUTDIR/seqmut"
        rm -f "$md.bin" "$md.map"
        sed "$2" "$ASM" > "$md.asm"
        if cmp -s "$ASM" "$md.asm"; then
          echo "FAIL  (SEQ mut) '$1': o alvo do sed nao existe mais em $(basename "$ASM")"
          fail=$((fail+1)); return
        fi
        ( cd "$OUTDIR" && "$ASAR" -DGBC_HARNESS=1 --symbols=wla \
            --symbols-path=seqmut.sym seqmut.asm seqmut.bin ) >"$md.log" 2>&1 &&
        $PY "$REPO_ROOT/snes/gbc/gen_map_asar.py" "$md.sym" "$md.bin" "$md.map" >>"$md.log" 2>&1
        if [ ! -f "$md.map" ]; then
          echo "FAIL  (SEQ mut) '$1' nao montou:"; sed 's/^/      /' "$md.log" | head -4
          fail=$((fail+1)); return
        fi
        if seq_run "$3" "$4" "$5" "$6" "$md.bin" "$md.map" >"$md.run.log" 2>&1; then
          echo "FAIL  (SEQ mut) '$1' passou -- a propriedade nao esta' sendo provada"
          fail=$((fail+1))
        else
          echo "PASS  (SEQ mut) '$1' derruba: $(grep -hm1 '^FAIL' "$md.run.log" | cut -c1-80)"
          pass=$((pass+1))
        fi
      }
      seq_mut "flags de sobra de cor zerados so' no GbcPcInit" \
        's/^\( *\)stz.b \$E[46]$/\1nop/' "$SEQC" "$SEQS" "" 1
      seq_mut "uma compilacao quita a divida dos dois conjuntos" \
        's/^\( *\)trb.b \$82           ; this set now carries these tables$/\1stz.b $82/' \
        "$SEQC" "$SEQS" "$SEQ1" 1
      seq_mut "a divida nunca e' quitada" \
        's/^\( *\)trb.b \$82           ; this set now carries these tables$/\1nop/' \
        "$SEQC" "$SEQS" "" 1
      # (No mutant for GbcRrGo's "wait for the set that owes": since the
      # prologue re-arms the set still owed, a claim on a set that owes
      # nothing only costs one redundant compile -- the wait is an
      # optimisation now, and a mutant without it converges.)
      seq_mut "prologo nao rearma o conjunto que ainda deve" \
        's/^\( *\)inc.b \$80           ; 1 = armed, the same inputs$/\1nop/' \
        "$SEQFX/dw3-fade-dream.views.bin" "$SEQFX/dw3-dream.views.bin" "$SEQALTB" 0
      seq_mut "CGRAM nao e' reenviada quando a cor sai do ar" \
        's/^\( *\)tsb.b \$3A           ; ... and has just left it.*/\1nop/' "$SEQC" "$SEQS" "" 1
    else
      echo "SKIP  (SEQ mut) 5 mutantes: $asar_why"; skip=$((skip+5))
    fi
  fi

  # -------------------------------------------------------------------------
  # (P5) THE V-IRQ -- the second read window, with the player FREE-RUNNING.
  #
  # Everything above pins V and calls GbcFrameOnce, so it can neither reach the
  # V-IRQ (a second entry into the frame body, pre-empted in turn by the NMI)
  # nor see time.  --clock runs the REAL main loop on m65816's clock: WAI, the
  # V-IRQ at VTIME and the NMI at V=225 dispatch through the ROM's own vectors,
  # DMAs and CPU accesses cost master cycles, the HDMA takes its sec. 11.1 tax,
  # and the CLI plays the bridge (LY=0 once per GB frame, 43 lines before SYNC
  # when locked; COMMIT publishes; CONSUMED closes; a LY=0 inside the window is
  # a skipped snapshot).  ALWAYS checked in that mode: no VRAM/CGRAM/OAM DMA on
  # a line the letterbox handed back (40..184), no CGRAM DMA over an HDMA line
  # with a colour channel up (S9), 1/1/1 strobes per frame, no view read
  # outside COMMIT..CONSUMED, the V-IRQ entered at most once a frame, and the
  # V-IRQ half never storing into the compiler's state or an HDMA set.
  #
  # The fixtures are the phase-4 ones (views built by the P4 block above).
  # -------------------------------------------------------------------------
  p5_planned=38
  P5FX="cgb-acid2 dmg-acid2 p4-cgb-colour p4b-oracle-ages"
  # All dirty once (the boot refresh), sixteen quiet frames for the screen to
  # be released -- before that $420C is 0 and no channel is on the bus -- and
  # then OAM/CRAM/map/chr changes with the HDMA running, colour channels
  # included where the fixture has them.
  P5DIRTY="all$(printf ';none%.0s' $(seq 1 15));map:0-3+oam+cram;none;chr:8-15+map:32-40;none;oam+cram;none;map:40-63+cram;none"
  # One dirty block at the END of four classes, every frame: each class is
  # scanned from its cursor to the last block, and the scans are long enough
  # that the V-IRQ half is still walking when the NMI comes -- the handoff's
  # second case (the IRQ half closes the frame itself).
  P5SPARSE='chr:47+obj:31+map:31+map:63'
  P5REQ="--require-virq 185 --require-window-b --require-snap-skipped-max 0 --require-nmi-delay-max 0 --require-sync-spread-max 128 --require-regs-late-max 0"
  # THE GbcRegs GUARD (GbcRegsSafe).  Nothing on the host clock reaches the
  # limit (!GBC_REGS_LAST), so the case makes the V-IRQ half as slow as a CPU
  # the model does not cover: 30 % dearer CPU (M65816_CPU_SCALE) AND a 22-line
  # stall of the V-IRQ handler once it owns the rest of the frame (--stall-irq,
  # sparse dirt so that it does).  The guard has to DEFER GbcRegs (counter) and
  # no store may reach $2107-$2114/$212C on an HDMA line -- that check is
  # always on in --clock; the mutant without the guard is what trips it.
  P5REGS="--frames 120 --stall-irq 226:22 --require-snap-skipped-max 0 --require-nmi-delay-max 0 --require-regs-late-min 1"
  if [ ! -f "$FIXTURES/manifest.json" ] || [ ! -f "$OUTDIR/p4_cgb-acid2.views.bin" ]; then
    if [ "$FIX_REQUIRED" != "0" ]; then
      echo "FAIL  (P5) fixtures da fase 4 ausentes"; fail=$((fail+1))
    else
      echo "SKIP  (P5) V-IRQ ($p5_planned casos): fixtures da fase 4 ausentes"; skip=$((skip+p5_planned))
    fi
  else
    ck() { # <views> <log> [args...]  -- a clocked run
      local v="$1" l="$2"; shift 2
      $CLI --rom "$BIN" --map "$MAP" --views "$OUTDIR/p4_$v.views.bin" --clock "$@" >"$l" 2>&1
    }
    ckval() { sed -n "s/.*[ :]$2=\([0-9-]*\).*/\1/p" "$1" | head -1; }

    # --- (i) the V-IRQ fires at V=185, opens the frame (COMMIT in window B),
    #     and costs nothing the contract cares about: no snapshot skipped with
    #     the genlock locked, no DMA holding the NMI back, SYNC steady.
    for fx in $P5FX; do
      if ck "$fx" "$OUTDIR/p5_virq_$fx.log" --frames 40 --dirty "$P5DIRTY" $P5REQ; then
        echo "PASS  (P5-VIRQ $fx) $(grep -h '^clock: irq' "$OUTDIR/p5_virq_$fx.log" | cut -c8-)"
        pass=$((pass+1))
      else
        echo "FAIL  (P5-VIRQ $fx):"; grep -hE '^(FAIL|m65816)' "$OUTDIR/p5_virq_$fx.log" | sed 's/^/      /' | head -5
        fail=$((fail+1))
      fi
    done
    # ... under a STORM (everything dirty every frame: window B always full,
    # its last DMA sized right against V=225) ...
    if ck p4-empty "$OUTDIR/p5_storm.log" --frames 60 --dirty all $P5REQ; then
      echo "PASS  (P5-VIRQ storm) $(grep -h '^clock: bytes' "$OUTDIR/p5_storm.log" | cut -c8-)"
      pass=$((pass+1))
    else
      echo "FAIL  (P5-VIRQ storm):"; grep -hE '^(FAIL|m65816)' "$OUTDIR/p5_storm.log" | sed 's/^/      /' | head -5
      fail=$((fail+1))
    fi
    # ... and the handoff's second case, exercised on purpose
    if ck cgb-acid2 "$OUTDIR/p5_sparse.log" --frames 120 --dirty "$P5SPARSE" $P5REQ \
          --require-resume-by-irq-min 20; then
      echo "PASS  (P5-VIRQ sparse) $(grep -h 'resume_by_irq' "$OUTDIR/p5_sparse.log" | cut -c8-)"
      pass=$((pass+1))
    else
      echo "FAIL  (P5-VIRQ sparse):"; grep -hE '^(FAIL|m65816)' "$OUTDIR/p5_sparse.log" | sed 's/^/      /' | head -5
      fail=$((fail+1))
    fi

    if M65816_CPU_SCALE=1.3 ck cgb-acid2 "$OUTDIR/p5_regs.log" --dirty "$P5SPARSE" $P5REGS; then
      echo "PASS  (P5-REGS) GbcRegs tardio adiado, nunca sobre a HDMA: $(grep -h 'regs_late' "$OUTDIR/p5_regs.log" | cut -c8-)"
      pass=$((pass+1))
    else
      echo "FAIL  (P5-REGS):"; grep -hE '^(FAIL|m65816)' "$OUTDIR/p5_regs.log" | sed 's/^/      /' | head -5
      fail=$((fail+1))
    fi

    # --- (iii) THE COMPILER DID NOT MOVE: the tables the player publishes
    #     after 60 free-running frames are the golden's, byte for byte, with the
    #     V-IRQ on and off.  ⚡ P5B: --settle lets the run finish a compile that
    #     is in flight when the frames run out (its counters are cleared at its
    #     start), which is what used to keep p4-log-512 and p4b-dkc-menu out of
    #     here -- their compiles ran ~3.000 and ~2.350 lines, and still take a
    #     few frames with the cheap compiler.
    for fx in cgb-acid2 dmg-acid2 p4-parallax p4-cgb-colour p4b-oracle-ages \
              p4b-dkc-menu p4-log-512; do
      for lk in 1 0; do
        rm -f "$OUTDIR/p5_gold.snst"
        ck "$fx" "$OUTDIR/p5_gold_$fx.$lk.log" --frames 60 --dirty 'all;none' --locked $lk \
           --settle --dump-snes "$OUTDIR/p5_gold.snst"
        if [ -f "$OUTDIR/p5_gold.snst" ] &&
           $PY "$OUTDIR/cmp_p4.py" "$OUTDIR/p5_gold.snst" "$FIXTURES/$fx" >"$OUTDIR/p5_gold.cmp" 2>&1; then
          echo "PASS  (P5-GOLD $fx locked=$lk) $(sed -n 1p "$OUTDIR/p5_gold.cmp")"
          pass=$((pass+1))
        else
          echo "FAIL  (P5-GOLD $fx locked=$lk):"
          { grep -hE '^(FAIL|m65816)' "$OUTDIR/p5_gold_$fx.$lk.log"; cat "$OUTDIR/p5_gold.cmp" 2>/dev/null; } | sed 's/^/      /' | head -6
          fail=$((fail+1))
        fi
      done
    done

    # --- (ii) THE WINDOW PAYS: a full refresh (everything dirty once) closes in
    #     fewer frames with window B than without it (locked=0 keeps the V-IRQ
    #     from opening the frame, i.e. the phase-4 body alone).
    for fx in p4-empty cgb-acid2 p4-cgb-colour; do
      ck "$fx" "$OUTDIR/p5_ref_$fx.1.log" --frames 40 --dirty 'all;none' --locked 1
      ck "$fx" "$OUTDIR/p5_ref_$fx.0.log" --frames 40 --dirty 'all;none' --locked 0
      r1=$(ckval "$OUTDIR/p5_ref_$fx.1.log" refresh_frames)
      r0=$(ckval "$OUTDIR/p5_ref_$fx.0.log" refresh_frames)
      if [ -n "$r1" ] && [ -n "$r0" ] && [ "$r1" -ge 0 ] && [ "$r0" -ge 0 ] && [ "$r1" -lt "$r0" ]; then
        echo "PASS  (P5-REFRESH $fx) refresh total em $r1 frames com a janela B, $r0 sem"
        pass=$((pass+1))
      else
        echo "FAIL  (P5-REFRESH $fx) refresh com janela B = '$r1', sem = '$r0'"
        fail=$((fail+1))
      fi
    done

    # --- (iv) FAIL-SAFE: a rev.1 5A22 and a PAL console never get the V-IRQ,
    #     and an unlocked genlock never has it enabled (GbcVirqArm).  rev.1 and
    #     PAL take the same path and run the SAME transfers at the SAME lines,
    #     DMA for DMA.  (Unlocked is the same body with GbcVirqArm's three
    #     extra instructions; on the clock that moves when a compile finishes,
    #     which moves a log copy by a frame -- so for it the check is "no V-IRQ,
    #     no window B, every invariant", not trace identity.)
    ck cgb-acid2 "$OUTDIR/p5_off_rev1.log" --frames 40 --dirty "$P5DIRTY" --cpurev 1 \
       --require-no-virq --trace-out "$OUTDIR/p5_off_rev1.tr"; a=$?
    ck cgb-acid2 "$OUTDIR/p5_off_pal.log" --frames 40 --dirty "$P5DIRTY" --pal --locked 1 \
       --require-no-virq --trace-out "$OUTDIR/p5_off_pal.tr"; b=$?
    ck cgb-acid2 "$OUTDIR/p5_off_unl.log" --frames 40 --dirty "$P5DIRTY" --locked 0 \
       --require-no-virq --trace-out "$OUTDIR/p5_off_unl.tr"; c=$?
    cb=$(ckval "$OUTDIR/p5_off_unl.log" commit_in_B)
    if [ $a = 0 ] && [ $b = 0 ] && [ $c = 0 ] && [ "$cb" = 0 ] &&
       cmp -s "$OUTDIR/p5_off_rev1.tr" "$OUTDIR/p5_off_pal.tr"; then
      echo "PASS  (P5-OFF) rev.1, PAL e genlock solto sem V-IRQ; rev.1 == PAL nas mesmas $(wc -l < "$OUTDIR/p5_off_rev1.tr" | tr -d ' ') DMAs, linha a linha"
      pass=$((pass+1))
    else
      echo "FAIL  (P5-OFF) rc=$a/$b/$c commit_in_B(solto)=$cb"
      grep -hE '^(FAIL|m65816)' "$OUTDIR"/p5_off_*.log | sed 's/^/      /' | head -5
      fail=$((fail+1))
    fi

    # --- (v) WHY THE GATE IS "LOCKED": with LY=0 drifting through the frame
    #     (Exato, or a genlock re-acquiring after an LCD toggle) every extra line
    #     the read window stays open is a line on which a snapshot is lost.
    #     Measured here; the mutant below removes the gate and must lose MORE.
    #     THREE drift rates, summed: one rate alone puts the result at the
    #     mercy of where LY=0 happens to fall against the player's own timing
    #     (the same player, drift 1.5 vs 1.6: +11 vs +2 over the closed
    #     window), so any change to the frame body's length moved the old
    #     single-rate "+2" in or out.  Summed over 1.0 / 1.6 / 2.6 the real
    #     gate stays within +7 % and the gate-less mutant loses +44 %.
    P5DRIFTS="1.0 1.6 2.6"
    p5_drift_sum() { # <rom> <map> <locked> <tag> -> the summed snap_skipped
      local rom="$1" map="$2" lk="$3" tag="$4" d v t=0
      for d in $P5DRIFTS; do
        $CLI --rom "$rom" --map "$map" --views "$OUTDIR/p4_cgb-acid2.views.bin" --clock \
             --frames 300 --dirty map:0-3+chr:0-3 --ly0-drift $d --locked $lk \
             >"$OUTDIR/p5_$tag.$d.log" 2>&1
        v=$(ckval "$OUTDIR/p5_$tag.$d.log" snap_skipped)
        [ -n "$v" ] || { echo ""; return; }
        t=$((t + v))
      done
      echo "$t"
    }
    # The bound the LOCKED run has to stay under AND the mutant has to break:
    # 15 % of the closed-window losses, never less than 6 snapshots.
    p5_exato_lim() { local b=$(( ($1 * 15 + 99) / 100 )); [ "$b" -lt 6 ] && b=6; echo $(( $1 + b )); }
    s0=$(p5_drift_sum "$BIN" "$MAP" 0 drift)
    echo "INFO  (P5-DRIFT) genlock solto, LY=0 derivando $P5DRIFTS linha/frame: snap_skipped somado = $s0 de 3 x 300 frames"
    # --- (v'') EXATO AS THE RTL PUBLISHES IT: gbc_clk.v reports
    #     `locked = exact_mode | locked_r`, so in Exato LOCKED is 1 and LY=0
    #     drifts 1.6 lines a frame.  LOCKED alone opened window B on every
    #     fresh frame and lost 115 snapshots here against the $s0 of the closed
    #     window; the LY_SYNC >= 25 gate (GbcVirqWanted) is what keeps it at or
    #     under the phase-4 body.  Bound: p5_exato_lim($s0) = $s0 + 15 %
    #     (min 6), summed over the three drift rates above.  Measured on
    #     cgb-acid2: this player 252 vs 235 closed (+7 %), the V-IRQ tree
    #     before P5B 253 vs 248 (+2 %), the gate-less mutant 339 (+44 %).
    P5EXATO="--frames 300 --dirty map:0-3+chr:0-3 --ly0-drift 1.6 --locked 1"
    s3=$(p5_drift_sum "$BIN" "$MAP" 1 exato)
    if [ -n "$s3" ] && [ -n "$s0" ] && [ "$s3" -le "$(p5_exato_lim "$s0")" ]; then
      echo "PASS  (P5-EXATO) LOCKED = 1 com LY=0 derivando: snap_skipped $s3 (janela B fechada: $s0, limite $(p5_exato_lim "$s0")), V-IRQ em $(ckval "$OUTDIR/p5_exato.1.6.log" irq_frames) frames a 1,6"
      pass=$((pass+1))
    else
      echo "FAIL  (P5-EXATO) snap_skipped $s3 com LOCKED = 1 em Exato contra $s0 com a janela B fechada (limite $( [ -n "$s0" ] && p5_exato_lim "$s0"))"
      fail=$((fail+1))
    fi

    # --- (v') RE-ACQUISITION: every 60 GB frames the LCD "toggles" and LY=0
    #     jumps to a new phase; the genlock pulls it back at 2.6 lines a frame
    #     and LOCKED returns after 8 frames within 64 dots.  LOCKED is a field
    #     OF THE SNAPSHOT, so a snapshot that window B swallows leaves it stale;
    #     GbcVirqWanted also demands a FRESH one ($3E b1).  Bound: the phase-4
    #     body on the same run (rev.1, no V-IRQ at all) plus at most ONE lost
    #     snapshot per re-acquisition -- the one frame a stale LOCKED can cost.
    P5RELOCK="--frames 600 --dirty map:0-3+chr:0-3 --relock-every 60"
    p5_nrel=10
    ck cgb-acid2 "$OUTDIR/p5_rl_rev1.log" $P5RELOCK --cpurev 1
    ck cgb-acid2 "$OUTDIR/p5_rl.log" $P5RELOCK
    r0=$(ckval "$OUTDIR/p5_rl_rev1.log" snap_skipped)
    r1=$(ckval "$OUTDIR/p5_rl.log" snap_skipped)
    # the same run with LOCKED published THREE frames late: the one place the
    # freshness test is still load-bearing now that LY_SYNC (live) closes
    # window B on the first SYNC after a phase jump.  (The RTL drops LOCKED on
    # LCD off and publishes the LCD-off snapshot, so an LCD toggle itself
    # does not leave it stale; a phase disturbance with the LCD on would.)
    ck cgb-acid2 "$OUTDIR/p5_rl3.log" $P5RELOCK --lock-lag 3
    r3=$(ckval "$OUTDIR/p5_rl3.log" snap_skipped)
    if [ -n "$r0" ] && [ -n "$r1" ] && [ "$r1" -le $((r0 + p5_nrel)) ]; then
      echo "PASS  (P5-RELOCK) snap_skipped $r1 com a V-IRQ, $r0 sem ela ($p5_nrel re-aquisicoes)"
      pass=$((pass+1))
    else
      echo "FAIL  (P5-RELOCK) snap_skipped $r1 com a V-IRQ contra $r0 sem ela (limite +$p5_nrel)"
      fail=$((fail+1))
    fi

    # --- MUTANTS.  Each one is a decision of the V-IRQ that a wrong player
    #     makes look almost right.
    if asar_ok; then
      p5_mutant() { # <nome> <caso: virq|drift> <fixture> <old> <new> [<old> <new>...]
        local nm="$1" kind="$2" fx="$3"
        local ma="$OUTDIR/p5mut.asm" mb="$OUTDIR/p5mut.bin" mm="$OUTDIR/p5mut.map"
        shift 3
        rm -f "$mm" "$mb"
