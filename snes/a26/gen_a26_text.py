def tile_of(glyph):
    """8x8 2bpp SNES tile: the glyph at x 1..5, y 0..6, outlined in colour 2."""
    px = [[0] * 8 for _ in range(8)]
    for y, row in enumerate(glyph):
        for x, c in enumerate(row):
            if c == "#":
                px[y][x + 1] = 1
    body = [r[:] for r in px]
    for y in range(8):
        for x in range(8):
            if body[y][x]:
                continue
            near = any(body[yy][xx] for yy in (y - 1, y, y + 1) for xx in (x - 1, x, x + 1)
                       if 0 <= yy < 8 and 0 <= xx < 8)
            if near:
                px[y][x] = 2
    out = []
    for y in range(8):
        p0 = p1 = 0
        for x in range(8):
            p0 |= (px[y][x] & 1) << (7 - x)
            p1 |= ((px[y][x] >> 1) & 1) << (7 - x)
        out += [p0, p1]
    return out


def main():
    chars = sorted({c for m in MESSAGES for c in m if c != " "})
    missing = [c for c in chars if c not in GLYPHS]
    assert not missing, "no glyph for %r" % missing
    index = {c: i + 1 for i, c in enumerate(chars)}      # tile 0 = blank
    L = ["; a26_text.inc -- GENERATED by gen_a26_text.py, do not edit by hand.",
         "; Font and messages of the on-screen text (BG2).", ""]
    L.append("!A26_TXT_TILES = %d" % (len(chars) + 1))
    L.append("!A26_TXT_COUNT = %d" % len(MESSAGES))
    L.append("")
    L.append("A26TxtFont:")
    L.append("    db " + ",".join(["$00"] * 16) + "  ; tile 0: blank")
    for c in chars:
        L.append("    db " + ",".join("$%02X" % b for b in tile_of(GLYPHS[c])) + "  ; '%s'" % c)
    L.append("A26TxtFontEnd:")
    L.append("")
    L.append("; one centred 32-entry BG2 row per message: palette 0, priority 1 ($2000)")
    L.append("A26TxtRows:")
    for i, m in enumerate(MESSAGES):
        assert len(m) <= 20, "message wider than the 160-pixel picture: " + m
        left = (32 - len(m)) // 2
        row = [0] * 32
        for k, c in enumerate(m):
            if c != " ":
                row[left + k] = index[c]
        L.append("    dw " + ",".join("$%04X" % (0x2000 | t if t else 0) for t in row) + "  ; %d %s" % (i, m))
    L.append("")
    with open(OUT, "w") as f:
        f.write("\n".join(L))
    print("wrote %s (%d glyphs, %d messages)" % (OUT, len(chars), len(MESSAGES)))


if __name__ == "__main__":
    main()
