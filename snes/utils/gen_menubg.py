#!/usr/bin/env python3
"""Generate the scrolling menu background (menubg_data.i65): a starfield over the theme's gradient.

The block is 128x128 low-res pixels on BG1 (mode 5, 4bpp), mostly transparent: the colour on the
screen is the gradient (black at the top, #004890 at the bottom). In mode 5 a BG1 tile is 16x8 HIRES
pixels, so every low-res pixel is drawn twice horizontally and a low-res 8x8 cell is a pair of tiles.
Cells equal up to a mirror share their tiles.

Output, in the order menubg.a65 uses them: menubg_pal (32 B), menubg_tiles (1024 B: 16 cells, each
its left tile then its right tile), menubg_map (256 words, 16x16 cells: cell * 2 | $4000 H | $8000 V).
The speed is BGX_DX_STEP / BGX_DY_STEP in menubg.a65. The landing's Theme Creator carries a copy of
all this in theme/bg.js: regenerate both.

  python3 utils/gen_menubg.py -o menubg_data.i65 [--preview out.png]
"""
import argparse
import random
import struct

W = H = 128           # block, low-res pixels
CW = CH = 16          # block, cells
NCELLS = 16           # what menubg.a65 uploads
NCOL = 16

CROSS = ["..2..", ".232.", "23432", ".232.", "..2.."]
SMALL = [".2.", "232", ".2."]
SPOTS = [(2, 2), (5, 1), (1, 5), (4, 4), (6, 6), (3, 6)]


def bgr555(r, g, b):
    return (b >> 3) << 10 | (g >> 3) << 5 | (r >> 3)


def palette():
    # entry 0 is transparent; three brightnesses of blue and a near white for the big stars' middle
    return [(0, 0, 0), (30, 70, 130), (70, 120, 190), (170, 210, 250), (245, 250, 255)] + [(0, 0, 0)] * 11


def block():
    """128x128 colour indices, 0 = transparent: one star at most per cell, in few shapes."""
    rnd = random.Random(7)
    px = [[0] * W for _ in range(H)]

    def stamp(sprite, x, y):
        for j, row in enumerate(sprite):
            for i, ch in enumerate(row):
                if ch != ".":
                    px[(y + j) % H][(x + i) % W] = int(ch)

    spots = [(rnd.randrange(0, CW), rnd.randrange(0, CH)) for _ in range(46)]
    used = set()
    for k, (cx, cy) in enumerate(spots):
        if (cx, cy) in used:
            continue
        used.add((cx, cy))
        ox, oy = SPOTS[k % len(SPOTS)]
        if k % 9 == 0:
            stamp(CROSS, cx * 8 + 1, cy * 8 + 1)
        elif k % 4 == 0:
            stamp(SMALL, cx * 8 + ox % 5, cy * 8 + oy % 5)
        else:
            px[(cy * 8 + oy) % H][(cx * 8 + ox) % W] = 1 + k % 2
    return px


def cells_and_map(px):
    """The distinct cells (rows of 8 low-res pixels) and the 256-word map."""
    cells, index, words = [], {}, []
    for cy in range(CH):
        for cx in range(CW):
            cell = tuple(tuple(px[cy * 8 + y][cx * 8 + x] for x in range(8)) for y in range(8))
            found = None
            for hflip in (0, 1):
                for vflip in (0, 1):
                    t = cell
                    if hflip:
                        t = tuple(tuple(reversed(r)) for r in t)
                    if vflip:
                        t = tuple(reversed(t))
                    if found is None and t in index:
                        found = index[t] * 2 | (0x4000 if hflip else 0) | (0x8000 if vflip else 0)
            if found is None:
                index[cell] = len(cells)
                found = len(cells) * 2
                cells.append(cell)
            words.append(found)
    if len(cells) > NCELLS:
        raise SystemExit(f"{len(cells)} cells, the block holds {NCELLS}")
    return cells, words


def tiles(cells):
    out = bytearray()
    for cell in cells:
        hi = [[cell[y][x // 2] for x in range(16)] for y in range(8)]
        for half in (0, 1):
            t = bytearray(32)
            for y in range(8):
                for x in range(8):
                    c = hi[y][half * 8 + x]
                    bit = 7 - x
                    t[y * 2] |= (c & 1) << bit
                    t[y * 2 + 1] |= ((c >> 1) & 1) << bit
                    t[16 + y * 2] |= ((c >> 2) & 1) << bit
                    t[16 + y * 2 + 1] |= ((c >> 3) & 1) << bit
            out += t
    return out.ljust(NCELLS * 64, b"\0")


def emit(name, data):
    lines = [f"{name}"]
    for i in range(0, len(data), 16):
        lines.append("  .byt " + ", ".join(f"${b:02x}" for b in data[i:i + 16]))
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("-o", required=True)
    ap.add_argument("--preview")
    a = ap.parse_args()
    pal = palette()
    px = block()
    cells, words = cells_and_map(px)
    pdat = bytearray()
    for r, g, b in pal:
        pdat += struct.pack("<H", bgr555(r, g, b))
    with open(a.o, "w") as f:
        f.write("// generated by utils/gen_menubg.py -- do not edit\n")
        f.write(emit("menubg_pal", pdat))
        f.write(emit("menubg_tiles", tiles(cells)))
        f.write(emit("menubg_map", b"".join(struct.pack("<H", w) for w in words)))
    if a.preview:
        from PIL import Image
        im = Image.new("RGB", (256, 224))
        for y in range(224):
            for x in range(256):
                c = px[y % H][x % W]
                im.putpixel((x, y), pal[c] if c else (0, 36, 72))
        im.save(a.preview)


if __name__ == "__main__":
    main()
