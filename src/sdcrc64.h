/* sdcrc64.h: the four DATx CRC16s of a 4-bit SD data block as ONE 64-bit CRC.

   Each data line carries its own CRC16-CCITT (x^16 + x^12 + x^5 + 1).  The lines are
   interleaved nibble by nibble, and four CRCs of interleaved streams are the CRC of the whole
   stream with the generator G(x^4) = x^64 + x^48 + x^20 + 1, so a block costs one table
   lookup per nibble, in the order the nibbles go on the bus (initial value 0):

     crc = (crc << 4) ^ sd_crc64_tab[(crc >> 60) ^ nibble]

   The result is already interleaved: its nibbles, most significant first, are the 16 CRC
   clocks the card expects (DAT3 = bit 3 of each nibble).

   Generated by:  r = i << 60; 4 x { r = (r << 1) ^ (0x0001000000100001 if r >> 63 else 0) }
*/
#ifndef SDCRC64_H
#define SDCRC64_H

#include <stdint.h>

static const uint64_t sd_crc64_tab[16] = {
  0x0000000000000000ULL, 0x0001000000100001ULL, 0x0002000000200002ULL, 0x0003000000300003ULL,
  0x0004000000400004ULL, 0x0005000000500005ULL, 0x0006000000600006ULL, 0x0007000000700007ULL,
  0x0008000000800008ULL, 0x0009000000900009ULL, 0x000a000000a0000aULL, 0x000b000000b0000bULL,
  0x000c000000c0000cULL, 0x000d000000d0000dULL, 0x000e000000e0000eULL, 0x000f000000f0000fULL,
};

#define SD_CRC64_NIB(crc, n) ((crc) = ((crc) << 4) ^ sd_crc64_tab[(uint32_t)((crc) >> 60) ^ (n)])

#endif
